    all_values = all_values[np.isfinite(all_values)]
    if all_values.size == 0:
        return payload
    resolved = max(1, int(_resolve_histogram_bin_count(all_values).get("bin_count") or 1))
    next_payload = dict(payload)
    next_payload["bin_count"] = resolved
    return next_payload


