def _build_plotstats_histogram_spec(
    metric: ProductionMetricSelection,
    groups: list[tuple[str, pd.DataFrame]],
    *,
    title: str,
    stats_tables: list[dict[str, Any]],
    plotly_visual_settings: dict[str, Any] | None = None,
) -> dict[str, Any] | None:
    payload_groups: list[dict[str, Any]] = []
    all_values: list[float] = []
    for label, group in groups:
        if metric.field_name not in group.columns:
            continue
        values = _finite_numeric_values(group[metric.field_name])
        if not values:
            continue
        payload_groups.append({"group": str(label), "values": values})
        all_values.extend(values)
    if not all_values:
        return None
    bin_count = int(resolve_histogram_bin_count(all_values).get("bin_count") or 0)
    payload: dict[str, Any] = {
        "type": "histogram",
        "title": title,
        "limits": _plotstats_metric_limits(metric),
        "style": {"axis_label_x": metric.display_label, "axis_label_y": "Frequency (%)"},
    }
    if len(payload_groups) == 1:
        payload["values"] = payload_groups[0]["values"]
    else:
        payload["groups"] = payload_groups
    if bin_count > 0:
        payload["bin_count"] = bin_count
    if stats_tables:
        payload["summary_table_rows"] = list(stats_tables[0].get("rows") or [])
    if plotly_visual_settings:
        payload["plotly_visual_settings"] = dict(plotly_visual_settings)
    spec = build_dashboard_plotly_spec(
        payload,
        title=title,
        theme=metroliza_dashboard_plotstats_theme(),
        static=False,
    )
    if spec and plotly_visual_settings:
        apply_dashboard_visual_settings(
            spec,
            payload=payload,
            visual_settings=plotly_visual_settings,
            theme=metroliza_dashboard_plotstats_theme(),
        )
    if spec:
        _apply_histogram_tick_readability(spec)
    return spec


def _build_plotstats_distribution_spec(
    metric: ProductionMetricSelection,
    groups: list[tuple[str, pd.DataFrame]],
    *,
    chart_type: str,
    title: str,
    plotly_visual_settings: dict[str, Any] | None = None,
) -> dict[str, Any] | None:
    labels: list[str] = []
    series: list[list[float]] = []
    for label, group in groups:
        if metric.field_name not in group.columns:
            continue
        values = _finite_numeric_values(group[metric.field_name])
        if not values:
            continue
        labels.append(str(label))
        series.append(values)
    if not series:
        return None

    if chart_type == "violin":
        payload_type = "distribution"
        render_mode = "violin"
    elif chart_type == "box":
        payload_type = "iqr"
        render_mode = "iqr"
    else:
        return None

    payload = {
        "type": payload_type,
        "render_mode": render_mode,
        "title": title,
        "labels": labels,
        "series": series,
        "limits": _plotstats_metric_limits(metric),
        "x_label": "Groups",
        "y_label": metric.display_label,
        "style": {"axis_label_x": "Groups", "axis_label_y": metric.display_label},
    }
    if plotly_visual_settings:
        payload["plotly_visual_settings"] = dict(plotly_visual_settings)
    spec = build_dashboard_plotly_spec(
        payload,
        title=title,
        theme=metroliza_dashboard_plotstats_theme(),
        static=False,
    )
    if spec and plotly_visual_settings:
        apply_dashboard_visual_settings(
            spec,
            payload=payload,
            visual_settings=plotly_visual_settings,
            theme=metroliza_dashboard_plotstats_theme(),
        )
    return spec


def _plotstats_metric_limits(metric: ProductionMetricSelection) -> dict[str, float | None]:
    lsl = _coerce_optional_float(metric.lsl)
    usl = _coerce_optional_float(metric.usl)
    nominal = ((lsl + usl) / 2.0) if lsl is not None and usl is not None and lsl <= usl else None
    return {"lsl": lsl, "nominal": nominal, "usl": usl}


def _raw_with_markers_x_axis_title(aggregation: ProductionAggregationState) -> str:
    if aggregation.is_aggregated and aggregation.time_bucket != "none":
        return _bucket_axis_title(aggregation.time_bucket)
    return "Process time"


def _apply_histogram_tick_readability(spec: dict[str, Any]) -> None:
    layout = spec.setdefault("layout", {})
    if not isinstance(layout, dict):
        return
    xaxis = layout.setdefault("xaxis", {})
    if not isinstance(xaxis, dict):
        return
    xaxis["tickformat"] = ".4~g"
    xaxis["tickfont"] = {"size": 10}
    xaxis["tickangle"] = -30
    xaxis["automargin"] = True
    title = xaxis.get("title")
    if isinstance(title, dict):
        title["standoff"] = max(int(title.get("standoff") or 0), 20)
    elif title:
        xaxis["title"] = {"text": str(title), "standoff": 20}
    else:
        xaxis["title"] = {"text": "", "standoff": 20}
    margin = layout.setdefault("margin", {})
    if isinstance(margin, dict):
        margin["b"] = max(int(margin.get("b") or 0), 92)


def _coerce_optional_float(value: Any) -> float | None:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if np.isfinite(number) else None


def _finite_numeric_values(series: pd.Series) -> list[float]:
    values = pd.to_numeric(series, errors="coerce").dropna().to_numpy(dtype=float)
    values = values[np.isfinite(values)]
    return [float(value) for value in values.tolist()]


