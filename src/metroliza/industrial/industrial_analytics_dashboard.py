def _render_time_series_density_layer_png(
    x_values: np.ndarray,
    y_values: np.ndarray,
    *,
    x_range: tuple[float, float],
    y_range: tuple[float, float],
    color: str,
    width: int = 1152,
    height: int = 456,
) -> tuple[bytes, int]:
    from PIL import Image
    from matplotlib.colors import to_rgb

    width = max(32, int(width))
    height = max(32, int(height))
    x = np.asarray(x_values, dtype=float)
    y = np.asarray(y_values, dtype=float)
    finite = np.isfinite(x) & np.isfinite(y)
    if not bool(np.any(finite)):
        return _transparent_png(width, height), 0
    x = x[finite]
    y = y[finite]
    x_min, x_max = float(x_range[0]), float(x_range[1])
    y_min, y_max = float(y_range[0]), float(y_range[1])
    if not np.isfinite(x_min) or not np.isfinite(x_max) or np.isclose(x_min, x_max):
        x_min = float(np.nanmin(x))
        x_max = float(np.nanmax(x))
        if np.isclose(x_min, x_max):
            x_max = x_min + 1.0
    if not np.isfinite(y_min) or not np.isfinite(y_max) or np.isclose(y_min, y_max):
        y_min = float(np.nanmin(y))
        y_max = float(np.nanmax(y))
        if np.isclose(y_min, y_max):
            y_min -= 0.5
            y_max += 0.5

    x_pixels = np.floor(((x - x_min) / (x_max - x_min)) * (width - 1)).astype(np.int64)
    y_pixels = np.floor(((y_max - y) / (y_max - y_min)) * (height - 1)).astype(np.int64)
    in_bounds = (
        (x_pixels >= 0)
        & (x_pixels < width)
        & (y_pixels >= 0)
        & (y_pixels < height)
    )
    if not bool(np.any(in_bounds)):
        return _transparent_png(width, height), 0
    flat_indexes = y_pixels[in_bounds] * width + x_pixels[in_bounds]
    counts = np.bincount(flat_indexes, minlength=width * height).reshape((height, width))
    non_empty = counts > 0
    non_empty_count = int(np.count_nonzero(non_empty))
    if non_empty_count <= 0:
        return _transparent_png(width, height), 0

    alpha_scale = np.log1p(counts.astype(np.float64))
    max_alpha = float(alpha_scale.max())
    alpha = np.zeros((height, width), dtype=np.uint8)
    if max_alpha > 0:
        alpha_values = 36.0 + (alpha_scale[non_empty] / max_alpha) * 204.0
        alpha[non_empty] = np.clip(alpha_values, 36, 240).astype(np.uint8)
    rgb = tuple(int(round(channel * 255)) for channel in to_rgb(color))
    image = np.zeros((height, width, 4), dtype=np.uint8)
    image[:, :, 0] = rgb[0]
    image[:, :, 1] = rgb[1]
    image[:, :, 2] = rgb[2]
    image[:, :, 3] = alpha
    buffer = BytesIO()
    Image.fromarray(image, mode="RGBA").save(buffer, format="PNG", optimize=True)
    buffer.seek(0)
    return buffer.getvalue(), non_empty_count


def _transparent_png(width: int, height: int) -> bytes:
    from PIL import Image

    buffer = BytesIO()
    Image.new("RGBA", (max(1, int(width)), max(1, int(height))), (0, 0, 0, 0)).save(
        buffer,
        format="PNG",
        optimize=True,
    )
    buffer.seek(0)
    return buffer.getvalue()


def _histogram_bins(values: list[float]) -> dict[str, float]:
    if not values:
        return {}
    minimum = min(values)
    maximum = max(values)
    if minimum == maximum:
        padding = max(abs(minimum) * 0.01, 0.5)
        minimum -= padding
        maximum += padding
    binning = resolve_histogram_bin_count(values)
    bin_count = max(1, int(binning.get("bin_count") or 1))
    bin_size = (maximum - minimum) / bin_count
    if bin_size <= 0:
        bin_size = 1.0
    return {"start": minimum, "end": maximum, "size": bin_size}


def _merge_axis_layout(base_layout: dict[str, Any], override: dict[str, Any]) -> None:
    for key, value in override.items():
        if key in {"xaxis", "yaxis"} and isinstance(value, dict):
            axis = base_layout.setdefault(key, {})
            axis.update(value)
            if axis.get("title") is not None and not isinstance(axis.get("title"), dict):
                axis["title"] = {"text": str(axis.get("title"))}
        elif key in {"shapes", "annotations"} and isinstance(value, list):
            base_layout.setdefault(key, [])
            base_layout[key].extend(value)
        else:
            base_layout[key] = value


def _apply_time_series_tick_readability(spec: dict[str, Any], *, chart_type: str) -> None:
    if not chart_type.startswith("time_series"):
        return
    layout = spec.get("layout")
    if not isinstance(layout, dict):
        return
    xaxis = layout.setdefault("xaxis", {})
    if not isinstance(xaxis, dict):
        return
    unique_count = _plotly_trace_unique_x_count(spec.get("data"))
    if unique_count < 16:
        return

    xaxis["automargin"] = True
    xaxis["tickangle"] = -34 if unique_count < 80 else -40
    xaxis["tickfont"] = {"size": 10 if unique_count < 200 else 9}
    xaxis["ticklabeloverflow"] = "hide past div"
    if unique_count >= 36:
        xaxis["ticklabelstep"] = max(2, min(8, int(np.ceil(unique_count / 24))))
        xaxis["nticks"] = max(6, min(12, int(np.ceil(unique_count / max(1, xaxis["ticklabelstep"])))))
    else:
        xaxis["nticks"] = max(8, min(14, int(np.ceil(unique_count / 2))))

    margin = layout.setdefault("margin", {})
    if isinstance(margin, dict):
        margin["b"] = max(int(margin.get("b") or 0), 86)


def _plotly_trace_unique_x_count(traces_payload: Any) -> int:
    if not isinstance(traces_payload, list):
        return 0
    seen: set[str] = set()
    for trace in traces_payload:
        if not isinstance(trace, dict):
            continue
        x_values = trace.get("x")
        if not isinstance(x_values, list):
            continue
        for value in x_values:
            if value is None:
                continue
            seen.add(str(value))
    return len(seen)


