def _plotly_chart_payloads(charts: list[Any]) -> list[dict[str, Any]]:
    payloads: list[dict[str, Any]] = []
    for chart in charts:
        if not isinstance(chart, dict) or not isinstance(chart.get("plotly_spec"), dict):
            continue
        payloads.append(
            {
                "id": chart.get("id"),
                "title": chart.get("title") or chart.get("id") or "Chart",
                "plotly_spec": chart.get("plotly_spec"),
                **(
                    {"optimization_options": chart.get("optimization_options")}
                    if isinstance(chart.get("optimization_options"), list)
                    else {}
                ),
            }
        )
    return payloads


def _dashboard_visual_preview_labels_from_charts(charts: list[Any]) -> tuple[str, ...]:
    labels: list[str] = []
    seen: set[str] = set()

    def add_label(raw_label: Any) -> None:
        label = _strip_group_count_suffix(str(raw_label or "").strip())
        key = label.casefold()
        if not key or key in seen:
            return
        seen.add(key)
        labels.append(label)

    for chart in charts:
        if not isinstance(chart, dict):
            continue
        for label in chart.get("group_labels") or []:
            add_label(label)
        for variant in _plotly_spec_variants(chart.get("plotly_spec")):
            for label in _series_labels_from_plotly_spec(variant):
                add_label(label)
    return dashboard_visual_preview_labels(labels)


def _series_labels_from_plotly_spec(spec: dict[str, Any]) -> list[str]:
    return _shared_series_labels_from_plotly_spec(
        spec,
        extra_generic_labels={"all production rows"},
    )


def _render_dashboard_section(*, section_id: str, title: str, body: str, subtitle: str = "") -> str:
    if not str(body or "").strip():
        return ""
    header = render_section_header(
        title,
        subtitle,
        actions=render_back_to_dashboard_start(),
    )
    return (
        f'<section id="{html.escape(section_id)}" class="measurement-section dashboard-section">'
        f"{header}{body}"
        "</section>"
    )


def _render_chart_section(chart: dict[str, Any], *, section_id: str) -> str:
    title = str(chart.get("title") or chart.get("id") or "Chart")
    subtitle_parts = [
        str(chart.get("chart_type") or "").replace("_", " ").title(),
        str(chart.get("field_name") or "").strip(),
    ]
    subtitle = " | ".join(part for part in subtitle_parts if part)
    header = render_section_header(
        title,
        subtitle,
        actions=render_back_to_dashboard_start(),
    )
    return (
        f'<section id="{html.escape(section_id)}" class="measurement-section dashboard-section">'
        f"{header}"
        f'<div class="chart-grid">{_render_chart_shell(chart)}</div>'
        "</section>"
    )


