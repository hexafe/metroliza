def _convert_static_population_layer(
    chart: dict[str, Any],
    *,
    option: dict[str, Any],
) -> dict[str, Any]:
    plotly_spec = chart.get("plotly_spec")
    if not isinstance(plotly_spec, dict) or not isinstance(plotly_spec.get("data"), list):
        option["skipped_reason"] = "missing_plotly_spec"
        return {"applied": False}
    traces = plotly_spec["data"]
    population_indexes = [
        index
        for index, trace in enumerate(traces)
        if _is_population_marker_trace(trace)
    ]
    if not population_indexes and _is_population_layer_label(option.get("group_label")):
        marker_indexes = [
            index
            for index, trace in enumerate(traces)
            if _is_static_population_candidate_marker_trace(trace)
        ]
        if len(marker_indexes) == 1:
            population_indexes = marker_indexes
    if len(population_indexes) != 1:
        option["skipped_reason"] = "ambiguous_population_layer"
        return {"applied": False}
    population_index = population_indexes[0]
    population_trace = traces[population_index]
    xy = _coerce_trace_xy(population_trace)
    if xy.empty:
        option["skipped_reason"] = "empty_population_layer"
        return {"applied": False}
    all_bounds = _plotly_trace_axis_bounds(traces)
    if not all_bounds:
        option["skipped_reason"] = "axis_bounds_unavailable"
        return {"applied": False}
    source_xy = _static_population_source_xy(option)
    if not source_xy.empty and str(source_xy["__x_mode"].iloc[0]) == str(all_bounds.get("x_mode")):
        render_xy = source_xy
        all_bounds = _axis_bounds_with_xy_frame(all_bounds, source_xy)
    else:
        render_xy = xy
    sample_limit = int(option.get("sample_point_limit") or DASHBOARD_RAW_POINT_LIMIT)
    color = _trace_color(population_trace) or _plot_color(population_index, "POPULATION")
    render_strategy = "marker_static"
    non_empty_pixel_count = None
    try:
        if len(render_xy.index) > _STATIC_POPULATION_DENSITY_POINT_THRESHOLD:
            png_bytes, non_empty_pixel_count = _render_time_series_density_layer_png(
                render_xy["__x_numeric"].to_numpy(dtype=float),
                render_xy["__y"].to_numpy(dtype=float),
                x_range=(all_bounds["x_min"], all_bounds["x_max"]),
                y_range=(all_bounds["y_min"], all_bounds["y_max"]),
                color=color,
            )
            render_strategy = "full_density"
        else:
            png_bytes = _render_time_series_raw_layer_png(
                render_xy["__x_numeric"].to_numpy(dtype=float),
                render_xy["__y"].to_numpy(dtype=float),
                x_range=(all_bounds["x_min"], all_bounds["x_max"]),
                y_range=(all_bounds["y_min"], all_bounds["y_max"]),
                color=color,
            )
    except Exception as exc:
        rendered_fallback = _sample_xy_frame(
            render_xy,
            min(len(render_xy.index), max(1, sample_limit)),
            seed=_stable_seed(
                str(chart.get("id") or ""),
                str(option.get("group_label") or "POPULATION"),
                "static-fallback",
            ),
        )
        png_bytes = _render_time_series_raw_layer_png(
            rendered_fallback["__x_numeric"].to_numpy(dtype=float),
            rendered_fallback["__y"].to_numpy(dtype=float),
            x_range=(all_bounds["x_min"], all_bounds["x_max"]),
            y_range=(all_bounds["y_min"], all_bounds["y_max"]),
            color=color,
        )
        render_xy = rendered_fallback
        render_strategy = "sampled_marker_fallback"
        option["render_warning"] = f"full_density_render_failed: {type(exc).__name__}"
    layout = plotly_spec.setdefault("layout", {})
    if not isinstance(layout, dict):
        layout = {}
        plotly_spec["layout"] = layout
    image_index = _append_static_population_layout_image(
        layout,
        png_bytes=png_bytes,
        label=str(option.get("group_label") or "POPULATION"),
        bounds=all_bounds,
    )
    traces.pop(population_index)
    traces.insert(
        population_index,
        _static_population_layer_proxy_trace(
            label=str(option.get("group_label") or "POPULATION"),
            color=color,
            image_index=image_index,
            render_strategy=render_strategy,
        ),
    )
    _apply_static_population_axis_ranges(layout, all_bounds)
    note = (
        "POPULATION layer rendered as a static image; hover and point selection are unavailable "
        "for that background layer."
    )
    if render_strategy == "full_density":
        note = (
            "POPULATION layer rendered as a static density image from all source points; "
            "hover and point selection are unavailable for that background layer."
        )
    elif render_strategy == "sampled_marker_fallback":
        note = (
            f"POPULATION layer rendered as a sampled static fallback with {len(render_xy.index):,} "
            "points; hover and point selection are unavailable for that background layer."
        )
    notes = list(chart.get("notes") or []) if isinstance(chart.get("notes"), list) else []
    if note not in notes:
        notes.append(note)
    chart["notes"] = notes
    rendered_count = int(len(render_xy.index))
    source_count = int(max(len(xy.index), int(option.get("source_point_count") or 0)))
    contributed_count = rendered_count if render_strategy == "sampled_marker_fallback" else source_count
    option.update(
        {
            "applied": True,
            "rendered_point_count": rendered_count,
            "source_point_count": source_count,
            "contributed_point_count": contributed_count,
            "render_strategy": render_strategy,
            "image_index": int(image_index),
            "raster_width": 900,
            "raster_height": 520,
        }
    )
    if non_empty_pixel_count is not None:
        option["non_empty_pixel_count"] = int(non_empty_pixel_count)
    return {
        "applied": True,
        "source_point_count": source_count,
        "rendered_point_count": rendered_count,
        "contributed_point_count": contributed_count,
        "render_strategy": render_strategy,
    }


def _is_population_marker_trace(trace: Any) -> bool:
    if not isinstance(trace, dict):
        return False
    if not _is_static_population_candidate_marker_trace(trace):
        return False
    return _is_population_layer_label(_population_trace_label(trace))


def _is_static_population_candidate_marker_trace(trace: Any) -> bool:
    if not isinstance(trace, dict):
        return False
    trace_type = str(trace.get("type") or "").casefold()
    mode = str(trace.get("mode") or "").casefold()
    return trace_type == "scatter" and "markers" in mode


def _population_trace_label(trace: dict[str, Any]) -> str:
    meta = trace.get("meta") if isinstance(trace.get("meta"), dict) else {}
    for candidate in (
        meta.get("metroliza_legend_label"),
        meta.get("metroliza_series_id"),
        trace.get("name"),
    ):
        label = _strip_group_count_suffix(str(candidate or "").strip())
        if label:
            return label
    return "POPULATION"


def _trace_point_count(trace: Any) -> int:
    if not isinstance(trace, dict):
        return 0
    x_values = trace.get("x")
    y_values = trace.get("y")
    if not isinstance(x_values, list) or not isinstance(y_values, list):
        return 0
    return min(len(x_values), len(y_values))


def _trace_color(trace: dict[str, Any]) -> str | None:
    marker = trace.get("marker") if isinstance(trace.get("marker"), dict) else {}
    color = marker.get("color")
    if isinstance(color, str) and color.strip():
        return color.strip()
    line = trace.get("line") if isinstance(trace.get("line"), dict) else {}
    color = line.get("color")
    if isinstance(color, str) and color.strip():
        return color.strip()
    return None


def _coerce_trace_xy(trace: dict[str, Any]) -> pd.DataFrame:
    x_values = trace.get("x")
    y_values = trace.get("y")
    if not isinstance(x_values, list) or not isinstance(y_values, list):
        return pd.DataFrame(columns=["__x_numeric", "__y", "__x_mode"])
    pair_count = min(len(x_values), len(y_values))
    raw = pd.DataFrame({"__x_raw": x_values[:pair_count], "__y_raw": y_values[:pair_count]})
    y_series = pd.to_numeric(raw["__y_raw"], errors="coerce")
    x_datetime = pd.to_datetime(raw["__x_raw"], errors="coerce", utc=True)
    non_null_x = int(raw["__x_raw"].notna().sum())
    datetime_count = int(x_datetime.notna().sum())
    if datetime_count and datetime_count >= max(1, int(non_null_x * 0.8)):
        x_numeric = x_datetime.astype("int64").astype(float) / 1_000_000.0
        mode = "date"
        valid_mask = x_datetime.notna() & y_series.notna()
    else:
        x_numeric = pd.to_numeric(raw["__x_raw"], errors="coerce")
        mode = "linear"
        valid_mask = x_numeric.notna() & y_series.notna()
    result = pd.DataFrame(
        {
            "__x_numeric": x_numeric.loc[valid_mask].astype(float),
            "__y": y_series.loc[valid_mask].astype(float),
        }
    )
    result = result.replace([np.inf, -np.inf], np.nan).dropna()
    result["__x_mode"] = mode
    return result


def _plotly_trace_axis_bounds(traces: list[Any]) -> dict[str, Any] | None:
    prepared = [
        xy
        for trace in traces
        if isinstance(trace, dict) and str(trace.get("type") or "").casefold() == "scatter"
        if not (xy := _coerce_trace_xy(trace)).empty
    ]
    if not prepared:
        return None
    x_modes = {str(xy["__x_mode"].iloc[0]) for xy in prepared}
    if len(x_modes) != 1:
        return None
    x_min = min(float(xy["__x_numeric"].min()) for xy in prepared)
    x_max = max(float(xy["__x_numeric"].max()) for xy in prepared)
    y_min = min(float(xy["__y"].min()) for xy in prepared)
    y_max = max(float(xy["__y"].max()) for xy in prepared)
    if np.isclose(x_min, x_max):
        x_max = x_min + 1.0
    if np.isclose(y_min, y_max):
        y_min -= 0.5
        y_max += 0.5
    else:
        padding = max((y_max - y_min) * 0.04, 1e-9)
        y_min -= padding
        y_max += padding
    return {
        "x_mode": next(iter(x_modes)),
        "x_min": x_min,
        "x_max": x_max,
        "y_min": y_min,
        "y_max": y_max,
    }


def _axis_bounds_with_xy_frame(
    bounds: dict[str, Any],
    xy: pd.DataFrame,
) -> dict[str, Any]:
    if xy.empty:
        return dict(bounds)
    merged = dict(bounds)
    merged["x_min"] = min(float(bounds["x_min"]), float(xy["__x_numeric"].min()))
    merged["x_max"] = max(float(bounds["x_max"]), float(xy["__x_numeric"].max()))
    merged["y_min"] = min(float(bounds["y_min"]), float(xy["__y"].min()))
    merged["y_max"] = max(float(bounds["y_max"]), float(xy["__y"].max()))
    if np.isclose(float(merged["x_min"]), float(merged["x_max"])):
        merged["x_max"] = float(merged["x_min"]) + 1.0
    if np.isclose(float(merged["y_min"]), float(merged["y_max"])):
        merged["y_min"] = float(merged["y_min"]) - 0.5
        merged["y_max"] = float(merged["y_max"]) + 0.5
    return merged


def _static_population_source_xy(option: dict[str, Any]) -> pd.DataFrame:
    source = option.get(_STATIC_POPULATION_SOURCE_XY_KEY)
    if isinstance(source, pd.DataFrame):
        required = {"__x_numeric", "__y", "__x_mode"}
        if required.issubset(source.columns):
            return source.replace([np.inf, -np.inf], np.nan).dropna(
                subset=["__x_numeric", "__y"]
            )
    return pd.DataFrame(columns=["__x_numeric", "__y", "__x_mode"])


