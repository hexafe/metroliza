def _metric_population_source_frame(
    source_frame: pd.DataFrame | None,
    metric_field_name: str,
    group_columns: list[str],
    *,
    default_name: str,
) -> pd.DataFrame | None:
    if source_frame is None or source_frame.empty:
        return None
    required_columns = ["process_datetime", metric_field_name, *group_columns]
    if any(column not in source_frame.columns for column in required_columns):
        return None
    population_group = _population_layer_group(
        source_frame,
        group_columns,
        default_name=default_name,
    )
    if population_group is None:
        return None
    _label, group = population_group
    return group.loc[group[metric_field_name].notna(), required_columns].copy()


def build_production_dashboard_manifest(
    *,
    frame: pd.DataFrame,
    metric_selection: tuple[ProductionMetricSelection, ...],
    aggregation_state: ProductionAggregationState | None = None,
    aggregation_result: ProductionAggregationResult | None = None,
    groupstats_result: ProductionGroupstatsResult | None = None,
    chart_selection: ProductionChartSelection | None = None,
    cohort_state: ReferenceCohortState | None = None,
    diagnostics: tuple[ProductionAnalyticsDiagnostic, ...] = (),
    dashboard_title: str = "Production Analytics",
    dashboard_subtitle: str = "Cached production data dashboard generated by Metroliza.",
    dashboard_context: dict[str, Any] | None = None,
    plotly_visual_settings: dict[str, Any] | None = None,
    include_plotly_specs: bool = True,
    dashboard_interactivity_options: Any = None,
    source_row_count: int | None = None,
    dashboard_row_count: int | None = None,
    static_population_source_frame: pd.DataFrame | None = None,
) -> dict[str, Any]:
    """Build a renderer-neutral manifest for the production analytics dashboard."""

    aggregation = aggregation_state or ProductionAggregationState()
    charts = chart_selection or ProductionChartSelection()
    cohort = cohort_state or ReferenceCohortState()
    interactivity = _normalize_dashboard_interactivity_options(dashboard_interactivity_options)
    population_layer_mode = str(interactivity.get("population_layer_mode") or "auto")
    rendered_row_count = int(dashboard_row_count if dashboard_row_count is not None else len(frame.index))
    selected_source_row_count = int(
        source_row_count if source_row_count is not None else len(frame.index)
    )
    aggregate_frame = (
        aggregation_result.dataframe
        if aggregation_result is not None and not aggregation_result.dataframe.empty
        else pd.DataFrame()
    )

    chart_specs: list[dict[str, Any]] = []
    for metric in metric_selection:
        if metric.field_name not in frame.columns:
            continue
        metric_frame = frame.loc[frame[metric.field_name].notna()]
        if metric_frame.empty:
            continue
        chart_group_columns = _chart_group_columns(metric_frame, aggregation)
        if charts.time_series:
            metric_population_source_frame = _metric_population_source_frame(
                static_population_source_frame,
                metric.field_name,
                chart_group_columns,
                default_name=metric.display_label,
            )
            specs = _build_time_series_charts(
                metric,
                raw_frame=metric_frame,
                static_population_source_frame=metric_population_source_frame,
                aggregate_frame=aggregate_frame,
                aggregation=aggregation,
                group_columns=chart_group_columns,
                plotly_visual_settings=plotly_visual_settings,
                include_plotly_specs=include_plotly_specs,
                population_layer_mode=population_layer_mode,
            )
            chart_specs.extend(spec for spec in specs if spec)
        if charts.histogram:
            spec = _build_histogram_chart(
                metric,
                metric_frame,
                group_columns=chart_group_columns,
                plotly_visual_settings=plotly_visual_settings,
                include_plotly_specs=include_plotly_specs,
            )
            if spec:
                chart_specs.append(spec)
        if charts.violin:
            spec = _build_distribution_chart(
                metric,
                metric_frame,
                chart_type="violin",
                group_columns=chart_group_columns,
                plotly_visual_settings=plotly_visual_settings,
                include_plotly_specs=include_plotly_specs,
            )
            if spec:
                chart_specs.append(spec)
        if charts.box:
            spec = _build_distribution_chart(
                metric,
                metric_frame,
                chart_type="box",
                group_columns=chart_group_columns,
                plotly_visual_settings=plotly_visual_settings,
                include_plotly_specs=include_plotly_specs,
            )
            if spec:
                chart_specs.append(spec)

    summary = {
        "generated_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        "source_rows": selected_source_row_count,
        "rows": rendered_row_count,
        "aggregate_rows": (
            int(aggregation_result.output_row_count)
            if aggregation_result is not None
            else 0
        ),
        "metric_count": len(metric_selection),
        "chart_count": len(chart_specs),
        "time_bucket": aggregation.time_bucket,
        "aggregation_methods": list(aggregation.aggregation_methods),
        "group_fields": list(aggregation.group_fields),
        "reference_cohort_count": len(cohort.references),
        "reference_cohort_mode": cohort.mode,
        "dashboard_title": dashboard_title,
        "dashboard_subtitle": dashboard_subtitle,
        "dashboard_context": dict(dashboard_context or {}),
        "groupstats_metric_count": (
            groupstats_result.analyzed_metric_count
            if groupstats_result is not None
            else 0
        ),
    }
    available_optimization_options = _available_chart_optimization_options(chart_specs)
    if available_optimization_options:
        summary["available_optimization_options"] = available_optimization_options
    return {
        "schema": DASHBOARD_SCHEMA,
        "summary": summary,
        "metrics": [
            {
                "field_name": metric.field_name,
                "display_label": metric.display_label,
                "source_kind": metric.source_kind,
            }
            for metric in metric_selection
        ],
        "charts": chart_specs,
        "groupstats": _groupstats_payload(groupstats_result),
        "diagnostics": [_diagnostic_payload(diagnostic) for diagnostic in diagnostics],
    }


def write_production_dashboard(
    manifest: dict[str, Any],
    output_path: str | Path,
    *,
    assets_dir: str | Path | None = None,
    plotly_spec_count_budget: int = DEFAULT_PLOTLY_SPEC_COUNT_BUDGET,
    plotly_serialized_json_bytes_budget: int = DEFAULT_PLOTLY_SERIALIZED_JSON_BYTES_BUDGET,
    dashboard_visual_settings: dict[str, Any] | None = None,
    dashboard_interactivity_options: Any = None,
) -> dict[str, Any]:
    """Write an offline production analytics dashboard and local Plotly asset."""

    destination = Path(output_path)
    if destination.suffix.lower() != ".html":
        destination = destination.with_suffix(".html")
    destination.parent.mkdir(parents=True, exist_ok=True)
    asset_directory = (
        Path(assets_dir)
        if assets_dir is not None
        else destination.with_name(f"{destination.stem}_assets")
    )
    plotly_spec_count = _count_plotly_specs(manifest)
    plotly_serialized_json_bytes = _measure_plotly_specs_json_bytes(manifest)
    count_budget = max(0, int(plotly_spec_count_budget))
    json_bytes_budget = max(0, int(plotly_serialized_json_bytes_budget))
    interactivity = _normalize_dashboard_interactivity_options(dashboard_interactivity_options)
    plotly_budget_status = "within_budget"
    plotly_budget_reason = ""
    base_dashboard_manifest = _copy_manifest_for_render(manifest)
    population_layer_summary = _apply_static_population_layer_options(
        base_dashboard_manifest,
        interactivity=interactivity,
    )
    dashboard_manifest = base_dashboard_manifest
    if interactivity["mode"] == "static" and plotly_spec_count > 0:
        dashboard_manifest = _copy_manifest_without_plotly_specs(
            base_dashboard_manifest,
            note_message=(
                "Interactive chart replaced with an image snapshot because Snapshots only "
                "mode was selected; summary content remains available."
            ),
        )
    else:
        dashboard_manifest, plotly_budget_status, plotly_budget_reason = (
            _copy_manifest_with_plotly_budget(
                base_dashboard_manifest,
                count_budget=count_budget,
                json_bytes_budget=json_bytes_budget,
            )
        )
    embedded_plotly_spec_count = _count_plotly_specs(dashboard_manifest)
    embedded_plotly_serialized_json_bytes = _measure_plotly_specs_json_bytes(dashboard_manifest)
    if (
        interactivity["mode"] != "static"
        and plotly_spec_count > 0
        and embedded_plotly_spec_count < plotly_spec_count
    ):
        plotly_budget_status = "over_budget"
        reasons = []
        if plotly_spec_count > count_budget:
            reasons.append(f"spec_count>{count_budget}")
        if plotly_serialized_json_bytes > json_bytes_budget:
            reasons.append(f"serialized_json_bytes>{json_bytes_budget}")
        if not reasons:
            reasons.append("specs_omitted")
        plotly_budget_reason = ",".join(reasons)

    asset_directory.mkdir(parents=True, exist_ok=True)
    plotly_runtime_status = "not_needed"
    if interactivity["mode"] == "static" and plotly_spec_count > 0:
        plotly_runtime_status = "static_snapshot_only"
    elif _manifest_requires_plotly(dashboard_manifest):
        plotly_js_path = _copy_plotly_runtime_asset(asset_directory)
        if plotly_js_path:
            plotly_runtime_status = "local"
        else:
            dashboard_manifest = _copy_manifest_without_plotly_specs(
                dashboard_manifest,
                note_message=(
                    "Interactive chart replaced with an image snapshot because the interactive "
                    "chart library was unavailable; summary and statistics remain available."
                ),
            )
            plotly_runtime_status = "snapshot_only"
    elif plotly_spec_count > 0 and plotly_budget_status == "over_budget":
        plotly_runtime_status = "budget_snapshot_only"

    embedded_plotly_spec_count = _count_plotly_specs(dashboard_manifest)
    embedded_plotly_serialized_json_bytes = _measure_plotly_specs_json_bytes(dashboard_manifest)
    _apply_dashboard_interactivity_summary(
        dashboard_manifest,
        interactivity,
        population_layer_summary=population_layer_summary,
    )
    _apply_plotly_budget_summary(
        dashboard_manifest,
        status=plotly_budget_status,
        reason=plotly_budget_reason,
    )
    _apply_plotly_runtime_summary(dashboard_manifest, status=plotly_runtime_status)
    _strip_static_population_private_payloads(dashboard_manifest)

    html_text = _render_dashboard_html(
        dashboard_manifest,
        asset_directory_name=asset_directory.name,
        dashboard_visual_settings=dashboard_visual_settings,
    )
    html_bytes = len(html_text.encode("utf-8"))
    destination.write_text(html_text, encoding="utf-8")
    return {
        "html_dashboard_path": str(destination),
        "html_dashboard_assets_path": str(asset_directory),
        "html_dashboard_chart_count": len(dashboard_manifest.get("charts") or []),
        "html_dashboard_interactive_chart_count": int(embedded_plotly_spec_count),
        "html_dashboard_plotly_spec_count": int(plotly_spec_count),
        "html_dashboard_embedded_plotly_spec_count": int(embedded_plotly_spec_count),
        "html_dashboard_plotly_serialized_json_bytes": int(plotly_serialized_json_bytes),
        "html_dashboard_embedded_plotly_serialized_json_bytes": int(
            embedded_plotly_serialized_json_bytes
        ),
        "html_dashboard_html_bytes": int(html_bytes),
        "html_dashboard_plotly_budget": {
            "status": plotly_budget_status,
            "reason": plotly_budget_reason,
            "spec_count_budget": int(count_budget),
            "serialized_json_bytes_budget": int(json_bytes_budget),
        },
        "html_dashboard_plotly_runtime_status": plotly_runtime_status,
        "html_dashboard_static_population_layer": population_layer_summary,
    }


def _manifest_requires_plotly(manifest: dict[str, Any]) -> bool:
    charts = manifest.get("charts") if isinstance(manifest.get("charts"), list) else []
    return any(isinstance(chart, dict) and isinstance(chart.get("plotly_spec"), dict) for chart in charts)


def _copy_manifest_for_render(manifest: dict[str, Any]) -> dict[str, Any]:
    manifest_copy = dict(manifest)
    summary = manifest.get("summary")
    if isinstance(summary, dict):
        manifest_copy["summary"] = dict(summary)
    charts = manifest.get("charts")
    if isinstance(charts, list):
        copied_charts: list[Any] = []
        for chart in charts:
            if not isinstance(chart, dict):
                copied_charts.append(chart)
                continue
            chart_copy = dict(chart)
            plotly_spec = chart.get("plotly_spec")
            if isinstance(plotly_spec, dict):
                chart_copy["plotly_spec"] = _clone_jsonable(plotly_spec)
            optimization_options = chart.get("optimization_options")
            if isinstance(optimization_options, list):
                chart_copy["optimization_options"] = _clone_optimization_options(
                    optimization_options
                )
            copied_charts.append(chart_copy)
        manifest_copy["charts"] = copied_charts
    return manifest_copy


def _clone_jsonable(value: Any) -> Any:
    return json.loads(json.dumps(value, ensure_ascii=False, default=str))


def _clone_optimization_options(options: list[Any]) -> list[Any]:
    cloned: list[Any] = []
    for option in options:
        if not isinstance(option, dict):
            cloned.append(_clone_jsonable(option))
            continue
        private_source = option.get(_STATIC_POPULATION_SOURCE_XY_KEY)
        public_option = {
            key: value
            for key, value in option.items()
            if key != _STATIC_POPULATION_SOURCE_XY_KEY
        }
        cloned_option = _clone_jsonable(public_option)
        if private_source is not None:
            cloned_option[_STATIC_POPULATION_SOURCE_XY_KEY] = private_source
        cloned.append(cloned_option)
    return cloned


def _strip_static_population_private_payloads(manifest: dict[str, Any]) -> None:
    charts = manifest.get("charts") if isinstance(manifest.get("charts"), list) else []
    for chart in charts:
        if not isinstance(chart, dict):
            continue
        options = chart.get("optimization_options")
        if not isinstance(options, list):
            continue
        for option in options:
            if isinstance(option, dict):
                option.pop(_STATIC_POPULATION_SOURCE_XY_KEY, None)


def _iter_plotly_specs(manifest: dict[str, Any]):
    charts = manifest.get("charts") if isinstance(manifest.get("charts"), list) else []
    for chart in charts:
        if not isinstance(chart, dict):
            continue
        plotly_spec = chart.get("plotly_spec")
        if isinstance(plotly_spec, dict) and plotly_spec:
            yield plotly_spec


def _count_plotly_specs(manifest: dict[str, Any]) -> int:
    return sum(1 for _spec in _iter_plotly_specs(manifest))


def _measure_plotly_specs_json_bytes(manifest: dict[str, Any]) -> int:
    total = 0
    for plotly_spec in _iter_plotly_specs(manifest):
        total += len(
            json.dumps(
                plotly_spec,
                ensure_ascii=False,
                separators=(",", ":"),
            ).encode("utf-8")
        )
    return int(total)


def _measure_plotly_spec_json_bytes(plotly_spec: dict[str, Any]) -> int:
    return int(
        len(
            json.dumps(
                plotly_spec,
                ensure_ascii=False,
                separators=(",", ":"),
            ).encode("utf-8")
        )
    )


def _normalize_dashboard_interactivity_options(options: Any) -> dict[str, int | str]:
    return normalize_dashboard_interactivity_mapping(
        options,
        default_sample_size=int(DASHBOARD_RAW_POINT_LIMIT),
        strict=False,
        min_sample_size=1,
        max_sample_size=None,
    )


def _apply_static_population_layer_options(
    manifest: dict[str, Any],
    *,
    interactivity: dict[str, int | str],
) -> dict[str, Any]:
    selected_mode = str(interactivity.get("population_layer_mode") or "auto")
    summary: dict[str, Any] = {
        "mode": selected_mode,
        "applied_chart_count": 0,
        "source_point_count": 0,
        "rendered_point_count": 0,
        "contributed_point_count": 0,
        "render_strategy_counts": {},
        "skipped_chart_count": 0,
    }
    manifest_summary = manifest.get("summary")
    if isinstance(manifest_summary, dict):
        sample_size = int(interactivity.get("sample_size") or DASHBOARD_RAW_POINT_LIMIT)
        summary["sample_size"] = sample_size
        source_row_count = int(manifest_summary.get("source_rows") or 0)
        rendered_row_count = int(manifest_summary.get("rows") or 0)
        if rendered_row_count and source_row_count > rendered_row_count:
            summary.update(
                {
                    "dashboard_sampled": True,
                    "source_row_count": source_row_count,
                    "dashboard_row_count": rendered_row_count,
                }
            )
    if selected_mode == "interactive":
        summary["status"] = "interactive"
        return summary
    if str(interactivity.get("mode") or "") == "static":
        summary["status"] = "dashboard_static"
        return summary

    charts = manifest.get("charts") if isinstance(manifest.get("charts"), list) else []
    for chart in charts:
        if not isinstance(chart, dict):
            continue
        option = _static_population_layer_option_for_chart(chart)
        if option is None:
            already_static = _static_population_layer_existing_result(
                chart,
                selected_mode=selected_mode,
            )
            if already_static is not None and selected_mode != "interactive":
                summary["applied_chart_count"] += 1
                summary["source_point_count"] += int(already_static.get("source_point_count") or 0)
                summary["rendered_point_count"] += int(already_static.get("rendered_point_count") or 0)
                summary["contributed_point_count"] += int(
                    already_static.get("contributed_point_count")
                    or already_static.get("rendered_point_count")
                    or 0
                )
                continue
            if selected_mode == "static" and _chart_has_population_like_plotly_trace(chart):
                _mark_static_population_layer_skipped(
                    chart,
                    reason="unsupported_chart_type",
                    message="Static POPULATION image layers are not available for this chart type yet.",
                )
                summary["skipped_chart_count"] += 1
            continue
        source_point_count = int(option.get("source_point_count") or 0)
        should_apply = selected_mode == "static" or (
            selected_mode == "auto" and source_point_count >= int(DASHBOARD_RAW_POINT_LIMIT)
        )
        option["selected_mode"] = selected_mode
        option["applied"] = False
        if not should_apply:
            option["skipped_reason"] = "below_auto_threshold"
            continue
        result = _convert_static_population_layer(chart, option=option)
        if result.get("applied"):
            summary["applied_chart_count"] += 1
            summary["source_point_count"] += int(result.get("source_point_count") or 0)
            summary["rendered_point_count"] += int(result.get("rendered_point_count") or 0)
            summary["contributed_point_count"] += int(result.get("contributed_point_count") or 0)
            render_strategy = str(result.get("render_strategy") or "").strip()
            if render_strategy:
                strategy_counts = summary["render_strategy_counts"]
                if isinstance(strategy_counts, dict):
                    strategy_counts[render_strategy] = int(strategy_counts.get(render_strategy) or 0) + 1
        else:
            summary["skipped_chart_count"] += 1
    if summary["applied_chart_count"]:
        summary["status"] = "applied"
    elif summary["skipped_chart_count"]:
        summary["status"] = "skipped"
    else:
        summary["status"] = "not_applicable"
    return summary


def _static_population_layer_existing_result(
    chart: dict[str, Any],
    *,
    selected_mode: str,
) -> dict[str, Any] | None:
    plotly_spec = chart.get("plotly_spec")
    if not isinstance(plotly_spec, dict):
        return None
    layout = plotly_spec.get("layout")
    images = layout.get("images") if isinstance(layout, dict) else None
    if not isinstance(images, list):
        return None
    static_image_indexes = [
        index
        for index, image in enumerate(images)
        if isinstance(image, dict)
        and image.get("visible") is not False
        and (
            image.get("metroliza_static_population_layer")
            or _is_population_layer_label(image.get("metroliza_static_population_layer_label"))
            or _is_population_layer_label(image.get("metroliza_raw_layer_label"))
        )
    ]
    if not static_image_indexes:
        return None
    source_point_count = 0
    rendered_point_count = 0
    contributed_point_count = 0
    raw_options = chart.get("optimization_options")
    if isinstance(raw_options, list):
        for option in raw_options:
            if not isinstance(option, dict):
                continue
            if option.get("id") != STATIC_POPULATION_LAYER_OPTIMIZATION:
                continue
            source_point_count += int(option.get("source_point_count") or 0)
            rendered_point_count += int(option.get("sample_point_limit") or 0)
            contributed_point_count += int(
                option.get("contributed_point_count")
                or option.get("sample_point_limit")
                or 0
            )
            option["applied"] = True
            option["selected_mode"] = selected_mode
            option["rendered_point_count"] = int(option.get("sample_point_limit") or 0)
            option.setdefault("contributed_point_count", int(option.get("sample_point_limit") or 0))
            option.setdefault("render_strategy", "sampled_marker_image")
    return {
        "applied": True,
        "source_point_count": source_point_count,
        "rendered_point_count": rendered_point_count,
        "contributed_point_count": contributed_point_count,
        "render_strategy": "sampled_marker_image",
    }


def _static_population_layer_option_for_chart(chart: dict[str, Any]) -> dict[str, Any] | None:
    chart_type = str(chart.get("chart_type") or "").casefold()
    if not _supports_static_population_layer(chart_type):
        return None
    plotly_spec = chart.get("plotly_spec")
    if not isinstance(plotly_spec, dict):
        return None
    traces = plotly_spec.get("data")
    if not isinstance(traces, list):
        return None
    population_indexes = [
        index
        for index, trace in enumerate(traces)
        if _is_population_marker_trace(trace)
    ]
    existing_option = _existing_static_population_layer_option(chart)
    if (
        not population_indexes
        and existing_option is not None
        and _is_population_layer_label(existing_option.get("group_label"))
    ):
        marker_indexes = [
            index
            for index, trace in enumerate(traces)
            if _is_static_population_candidate_marker_trace(trace)
        ]
        if len(marker_indexes) == 1:
            population_indexes = marker_indexes
    if len(population_indexes) != 1:
        return None
    population_trace = traces[population_indexes[0]]
    trace_point_count = _trace_point_count(population_trace)
    existing_source_count = (
        int(existing_option.get("source_point_count") or 0)
        if isinstance(existing_option, dict)
        else 0
    )
    source_point_count = max(int(trace_point_count), int(existing_source_count))
    if source_point_count <= 0 or trace_point_count <= 0:
        return None
    option = _ensure_static_population_layer_option(chart)
    option.update(
        {
            "id": STATIC_POPULATION_LAYER_OPTIMIZATION,
            "available": True,
            "reason": "population_marker_layer_available",
            "group_label": _population_trace_label(population_trace),
            "source_point_count": int(source_point_count),
            "plotly_trace_point_count": int(trace_point_count),
            "sample_point_limit": int(DASHBOARD_RAW_POINT_LIMIT),
            "supported": True,
            "applied": False,
        }
    )
    return option


def _existing_static_population_layer_option(chart: dict[str, Any]) -> dict[str, Any] | None:
    raw_options = chart.get("optimization_options")
    if not isinstance(raw_options, list):
        return None
    for option in raw_options:
        if isinstance(option, dict) and option.get("id") == STATIC_POPULATION_LAYER_OPTIMIZATION:
            return option
    return None


def _ensure_static_population_layer_option(chart: dict[str, Any]) -> dict[str, Any]:
    raw_options = chart.get("optimization_options")
    options = raw_options if isinstance(raw_options, list) else []
    for option in options:
        if isinstance(option, dict) and option.get("id") == STATIC_POPULATION_LAYER_OPTIMIZATION:
            return option
    option: dict[str, Any] = {"id": STATIC_POPULATION_LAYER_OPTIMIZATION}
    options.append(option)
    chart["optimization_options"] = options
    return option


def _supports_static_population_layer(chart_type: str) -> bool:
    return chart_type.startswith("time_series") or chart_type in {"scatter", "point_series"}


def _chart_has_population_like_plotly_trace(chart: dict[str, Any]) -> bool:
    plotly_spec = chart.get("plotly_spec")
    if not isinstance(plotly_spec, dict) or not isinstance(plotly_spec.get("data"), list):
        return False
    return any(_is_population_marker_trace(trace) for trace in plotly_spec["data"])


