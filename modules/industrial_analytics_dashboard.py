def build_production_dashboard_manifest(
    *,
    frame: pd.DataFrame,
    metric_selection: tuple[ProductionMetricSelection, ...],
    aggregation_state: ProductionAggregationState | None = None,
    aggregation_result: ProductionAggregationResult | None = None,
    groupstats_result: ProductionGroupstatsResult | None = None,
    chart_selection: ProductionChartSelection | None = None,
    cohort_state: ReferenceCohortState | None = None,
    diagnostics: tuple[ProductionAnalyticsDiagnostic, ...] = (),
    dashboard_title: str = "Production Analytics",
    dashboard_subtitle: str = "Cached production data dashboard generated by Metroliza.",
    plotly_visual_settings: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Build a renderer-neutral manifest for the production analytics dashboard."""

    aggregation = aggregation_state or ProductionAggregationState()
    charts = chart_selection or ProductionChartSelection()
    cohort = cohort_state or ReferenceCohortState()
    aggregate_frame = (
        aggregation_result.dataframe
        if aggregation_result is not None and not aggregation_result.dataframe.empty
        else pd.DataFrame()
    )

    chart_specs: list[dict[str, Any]] = []
    for metric in metric_selection:
        if metric.field_name not in frame.columns:
            continue
        metric_frame = frame.loc[frame[metric.field_name].notna()]
        if metric_frame.empty:
            continue
        chart_group_columns = _chart_group_columns(metric_frame, aggregation)
        if charts.time_series:
            specs = _build_time_series_charts(
                metric,
                raw_frame=metric_frame,
                aggregate_frame=aggregate_frame,
                aggregation=aggregation,
                group_columns=chart_group_columns,
                plotly_visual_settings=plotly_visual_settings,
            )
            chart_specs.extend(spec for spec in specs if spec)
        if charts.histogram:
            spec = _build_histogram_chart(
                metric,
                metric_frame,
                group_columns=chart_group_columns,
                plotly_visual_settings=plotly_visual_settings,
            )
            if spec:
                chart_specs.append(spec)
        if charts.violin:
            spec = _build_distribution_chart(
                metric,
                metric_frame,
                chart_type="violin",
                group_columns=chart_group_columns,
                plotly_visual_settings=plotly_visual_settings,
            )
            if spec:
                chart_specs.append(spec)
        if charts.box:
            spec = _build_distribution_chart(
                metric,
                metric_frame,
                chart_type="box",
                group_columns=chart_group_columns,
                plotly_visual_settings=plotly_visual_settings,
            )
            if spec:
                chart_specs.append(spec)

    summary = {
        "generated_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        "source_rows": int(len(frame.index)),
        "aggregate_rows": (
            int(aggregation_result.output_row_count)
            if aggregation_result is not None
            else 0
        ),
        "metric_count": len(metric_selection),
        "chart_count": len(chart_specs),
        "time_bucket": aggregation.time_bucket,
        "aggregation_methods": list(aggregation.aggregation_methods),
        "group_fields": list(aggregation.group_fields),
        "reference_cohort_count": len(cohort.references),
        "reference_cohort_mode": cohort.mode,
        "dashboard_title": dashboard_title,
        "dashboard_subtitle": dashboard_subtitle,
        "groupstats_metric_count": (
            groupstats_result.analyzed_metric_count
            if groupstats_result is not None
            else 0
        ),
    }
    return {
        "schema": DASHBOARD_SCHEMA,
        "summary": summary,
        "metrics": [
            {
                "field_name": metric.field_name,
                "display_label": metric.display_label,
                "source_kind": metric.source_kind,
            }
            for metric in metric_selection
        ],
        "charts": chart_specs,
        "groupstats": _groupstats_payload(groupstats_result),
        "diagnostics": [_diagnostic_payload(diagnostic) for diagnostic in diagnostics],
    }


def write_production_dashboard(
    manifest: dict[str, Any],
    output_path: str | Path,
    *,
    assets_dir: str | Path | None = None,
    plotly_spec_count_budget: int = DEFAULT_PLOTLY_SPEC_COUNT_BUDGET,
    plotly_serialized_json_bytes_budget: int = DEFAULT_PLOTLY_SERIALIZED_JSON_BYTES_BUDGET,
    dashboard_visual_settings: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Write an offline production analytics dashboard and local Plotly asset."""

    destination = Path(output_path)
    if destination.suffix.lower() != ".html":
        destination = destination.with_suffix(".html")
    destination.parent.mkdir(parents=True, exist_ok=True)
    asset_directory = (
        Path(assets_dir)
        if assets_dir is not None
        else destination.with_name(f"{destination.stem}_assets")
    )
    plotly_spec_count = _count_plotly_specs(manifest)
    plotly_serialized_json_bytes = _measure_plotly_specs_json_bytes(manifest)
    count_budget = max(0, int(plotly_spec_count_budget))
    json_bytes_budget = max(0, int(plotly_serialized_json_bytes_budget))
    over_count_budget = plotly_spec_count > count_budget
    over_json_budget = plotly_serialized_json_bytes > json_bytes_budget
    plotly_budget_status = "within_budget"
    plotly_budget_reason = ""
    dashboard_manifest = _copy_manifest_for_render(manifest)
    if plotly_spec_count > 0 and (over_count_budget or over_json_budget):
        dashboard_manifest = _copy_manifest_without_plotly_specs(manifest)
        plotly_budget_status = "over_budget"
        reasons = []
        if over_count_budget:
            reasons.append(f"spec_count>{count_budget}")
        if over_json_budget:
            reasons.append(f"serialized_json_bytes>{json_bytes_budget}")
        plotly_budget_reason = ",".join(reasons)

    asset_directory.mkdir(parents=True, exist_ok=True)
    plotly_runtime_status = "not_needed"
    if _manifest_requires_plotly(dashboard_manifest):
        plotly_js_path = _copy_plotly_runtime_asset(asset_directory)
        if plotly_js_path:
            plotly_runtime_status = "local"
        else:
            dashboard_manifest = _copy_manifest_without_plotly_specs(
                dashboard_manifest,
                note_message=(
                    "Interactive chart omitted because the bundled Plotly runtime asset was "
                    "unavailable; summary/statistics remain available."
                ),
            )
            plotly_runtime_status = "snapshot_only"
    elif plotly_spec_count > 0 and plotly_budget_status == "over_budget":
        plotly_runtime_status = "budget_snapshot_only"

    embedded_plotly_spec_count = _count_plotly_specs(dashboard_manifest)
    embedded_plotly_serialized_json_bytes = _measure_plotly_specs_json_bytes(dashboard_manifest)
    _apply_plotly_budget_summary(
        dashboard_manifest,
        status=plotly_budget_status,
        reason=plotly_budget_reason,
    )
    _apply_plotly_runtime_summary(dashboard_manifest, status=plotly_runtime_status)

    html_text = _render_dashboard_html(
        dashboard_manifest,
        asset_directory_name=asset_directory.name,
        dashboard_visual_settings=dashboard_visual_settings,
    )
    html_bytes = len(html_text.encode("utf-8"))
    destination.write_text(html_text, encoding="utf-8")
    return {
        "html_dashboard_path": str(destination),
        "html_dashboard_assets_path": str(asset_directory),
        "html_dashboard_chart_count": len(dashboard_manifest.get("charts") or []),
        "html_dashboard_interactive_chart_count": int(embedded_plotly_spec_count),
        "html_dashboard_plotly_spec_count": int(plotly_spec_count),
        "html_dashboard_embedded_plotly_spec_count": int(embedded_plotly_spec_count),
        "html_dashboard_plotly_serialized_json_bytes": int(plotly_serialized_json_bytes),
        "html_dashboard_embedded_plotly_serialized_json_bytes": int(
            embedded_plotly_serialized_json_bytes
        ),
        "html_dashboard_html_bytes": int(html_bytes),
        "html_dashboard_plotly_budget": {
            "status": plotly_budget_status,
            "reason": plotly_budget_reason,
            "spec_count_budget": int(count_budget),
            "serialized_json_bytes_budget": int(json_bytes_budget),
        },
        "html_dashboard_plotly_runtime_status": plotly_runtime_status,
    }


def _manifest_requires_plotly(manifest: dict[str, Any]) -> bool:
    charts = manifest.get("charts") if isinstance(manifest.get("charts"), list) else []
    return any(isinstance(chart, dict) and isinstance(chart.get("plotly_spec"), dict) for chart in charts)


def _copy_manifest_for_render(manifest: dict[str, Any]) -> dict[str, Any]:
    manifest_copy = dict(manifest)
    summary = manifest.get("summary")
    if isinstance(summary, dict):
        manifest_copy["summary"] = dict(summary)
    return manifest_copy


def _iter_plotly_specs(manifest: dict[str, Any]):
    charts = manifest.get("charts") if isinstance(manifest.get("charts"), list) else []
    for chart in charts:
        if not isinstance(chart, dict):
            continue
        plotly_spec = chart.get("plotly_spec")
        if isinstance(plotly_spec, dict) and plotly_spec:
            yield plotly_spec


def _count_plotly_specs(manifest: dict[str, Any]) -> int:
    return sum(1 for _spec in _iter_plotly_specs(manifest))


def _measure_plotly_specs_json_bytes(manifest: dict[str, Any]) -> int:
    total = 0
    for plotly_spec in _iter_plotly_specs(manifest):
        total += len(
            json.dumps(
                plotly_spec,
                ensure_ascii=False,
                separators=(",", ":"),
            ).encode("utf-8")
        )
    return int(total)


def _resolve_bundled_plotly_js_path() -> Path:
    return PLOTLY_ASSET_SOURCE


def _copy_plotly_runtime_asset(asset_directory: Path) -> str | None:
    source_path = _resolve_bundled_plotly_js_path()
    if not source_path.exists():
        return None
    destination_path = asset_directory / PLOTLY_ASSET_NAME
    if not destination_path.exists():
        shutil.copy2(source_path, destination_path)
    return f"{asset_directory.name}/{destination_path.name}"


def _copy_manifest_without_plotly_specs(
    manifest: dict[str, Any],
    *,
    note_message: str | None = None,
) -> dict[str, Any]:
    note = note_message or (
        "Interactive chart omitted because the Plotly payload exceeded the dashboard "
        "budget; summary/statistics remain available."
    )
    pruned_manifest = dict(manifest)
    summary = manifest.get("summary")
    if isinstance(summary, dict):
        pruned_manifest["summary"] = dict(summary)
    charts = manifest.get("charts") if isinstance(manifest.get("charts"), list) else []
    pruned_charts: list[Any] = []
    for chart in charts:
        if not isinstance(chart, dict):
            pruned_charts.append(chart)
            continue
        chart_copy = dict(chart)
        if not isinstance(chart.get("plotly_spec"), dict):
            pruned_charts.append(chart_copy)
            continue
        chart_copy.pop("plotly_spec", None)
        raw_notes = chart_copy.get("notes")
        notes = list(raw_notes) if isinstance(raw_notes, list) else []
        chart_copy["notes"] = notes
        if isinstance(notes, list):
            notes.append(note)
        pruned_charts.append(chart_copy)
    pruned_manifest["charts"] = pruned_charts
    return pruned_manifest


def _apply_plotly_budget_summary(
    manifest: dict[str, Any],
    *,
    status: str,
    reason: str,
) -> None:
    summary = manifest.get("summary")
    if not isinstance(summary, dict):
        return
    summary["plotly_budget_status"] = status
    if reason:
        summary["plotly_budget_reason"] = reason
    else:
        summary.pop("plotly_budget_reason", None)


def _apply_plotly_runtime_summary(
    manifest: dict[str, Any],
    *,
    status: str,
) -> None:
    summary = manifest.get("summary")
    if isinstance(summary, dict):
        summary["plotly_runtime_status"] = status


def _build_time_series_charts(
    metric: ProductionMetricSelection,
    *,
    raw_frame: pd.DataFrame,
    aggregate_frame: pd.DataFrame,
    aggregation: ProductionAggregationState,
    group_columns: list[str] | None = None,
    plotly_visual_settings: dict[str, Any] | None = None,
) -> list[dict[str, Any]]:
    method = aggregation.aggregation_methods[0] if aggregation.aggregation_methods else "mean"
    aggregate_metric = f"{metric.field_name}__{method}"
    group_columns = group_columns or []
    charts: list[dict[str, Any]] = []
    raw_point_count = _time_series_point_count(
        raw_frame,
        x_column="process_datetime",
        y_column=metric.field_name,
    )
    use_hybrid_raw = raw_point_count > DASHBOARD_RAW_POINT_LIMIT
    raw_with_markers_x_axis_title = _raw_with_markers_x_axis_title(aggregation)
    if (
        aggregation.is_aggregated
        and not aggregate_frame.empty
        and "time_bucket_start" in aggregate_frame.columns
        and aggregate_metric in aggregate_frame.columns
        and all(column in aggregate_frame.columns for column in group_columns)
    ):
        traces = _time_series_traces(
            aggregate_frame,
            x_column="time_bucket_start",
            y_column=aggregate_metric,
            group_columns=group_columns,
            default_name=f"{metric.display_label} ({method})",
            time_bucket=aggregation.time_bucket,
        )
        if traces:
            charts.append(
                _chart_payload(
                    chart_id=f"time-series-{metric.field_name}-aggregated",
                    title=f"{metric.display_label} over time ({method})",
                    chart_type="time_series",
                    data=traces,
                    layout={
                        "xaxis": {"title": _bucket_axis_title(aggregation.time_bucket)},
                        "yaxis": {"title": f"{metric.display_label} ({method})"},
                        "hovermode": "x unified",
                    },
                    plotly_visual_settings=plotly_visual_settings,
                )
            )
            overlay_traces = _time_series_traces(
                aggregate_frame,
                x_column="time_bucket_start",
                y_column=aggregate_metric,
                group_columns=group_columns,
                default_name=f"{metric.display_label} aggregate",
                time_bucket=None if use_hybrid_raw else aggregation.time_bucket,
                aggregate_marker=True,
            )
            if use_hybrid_raw:
                hybrid = _build_hybrid_time_series_chart(
                    metric,
                    raw_frame=raw_frame,
                    aggregate_traces=overlay_traces,
                    group_columns=group_columns,
                    chart_id=f"time-series-{metric.field_name}-raw-aggregate",
                    title=f"{metric.display_label} raw values with {method} markers",
                    chart_type="time_series_raw_aggregate",
                    x_axis_title=raw_with_markers_x_axis_title,
                    y_axis_title=metric.display_label,
                    plotly_visual_settings=plotly_visual_settings,
                )
                if hybrid:
                    charts.append(hybrid)
                return charts
            raw_traces = _time_series_traces(
                raw_frame,
                x_column="process_datetime",
                y_column=metric.field_name,
                group_columns=group_columns,
                default_name=metric.display_label,
            )
            raw_traces.extend(overlay_traces)
            if raw_traces:
                charts.append(
                    _chart_payload(
                        chart_id=f"time-series-{metric.field_name}-raw-aggregate",
                        title=f"{metric.display_label} raw values with {method} markers",
                        chart_type="time_series_raw_aggregate",
                        data=raw_traces,
                        layout={
                            "xaxis": {"title": raw_with_markers_x_axis_title},
                            "yaxis": {"title": metric.display_label},
                            "hovermode": "closest",
                        },
                        plotly_visual_settings=plotly_visual_settings,
                    )
                )
        return charts

    if use_hybrid_raw:
        hybrid = _build_hybrid_time_series_chart(
            metric,
            raw_frame=raw_frame,
            aggregate_traces=_display_aggregate_time_series_traces(
                raw_frame,
                x_column="process_datetime",
                y_column=metric.field_name,
                group_columns=group_columns,
                default_name=f"{metric.display_label} aggregate",
            ),
            group_columns=group_columns,
            chart_id=f"time-series-{metric.field_name}",
            title=f"{metric.display_label} over time",
            chart_type="time_series",
            x_axis_title="Process time",
            y_axis_title=metric.display_label,
            plotly_visual_settings=plotly_visual_settings,
        )
        return [hybrid] if hybrid else []

    traces = _time_series_traces(
        raw_frame,
        x_column="process_datetime",
        y_column=metric.field_name,
        group_columns=group_columns,
        default_name=metric.display_label,
    )
    if not traces:
        return []
    return [
        _chart_payload(
            chart_id=f"time-series-{metric.field_name}",
            title=f"{metric.display_label} over time",
            chart_type="time_series",
            data=traces,
            layout={
                "xaxis": {"title": "Process time"},
                "yaxis": {"title": metric.display_label},
                "hovermode": "x unified",
            },
            plotly_visual_settings=plotly_visual_settings,
        )
    ]


def _build_histogram_chart(
    metric: ProductionMetricSelection,
    frame: pd.DataFrame,
    *,
    group_columns: list[str] | None = None,
    plotly_visual_settings: dict[str, Any] | None = None,
) -> dict[str, Any]:
    groups = _plot_groups(frame, group_columns=group_columns)
    image_groups, sampling_note = _sample_plot_groups_for_static_image(
        groups,
        metric.field_name,
        seed_parts=("histogram", metric.field_name),
    )
    stats_tables = _histogram_stats_tables(metric, groups)
    plotly_spec = _build_plotstats_histogram_spec(
        metric,
        image_groups,
        title=f"{metric.display_label} distribution",
        stats_tables=stats_tables,
        plotly_visual_settings=plotly_visual_settings,
    )
    image = _render_distribution_image(metric, frame, chart_type="histogram", groups=image_groups)
    if not stats_tables and not image and plotly_spec is None:
        return {}
    chart = _static_chart_payload(
        chart_id=f"histogram-{metric.field_name}",
        title=f"{metric.display_label} distribution",
        chart_type="histogram",
        group_labels=[label for label, _group in groups],
        image=image,
        stats_tables=stats_tables,
        notes=([sampling_note] if sampling_note else []),
    )
    if plotly_spec is not None:
        chart["plotly_spec"] = plotly_spec
    return chart


def _build_distribution_chart(
    metric: ProductionMetricSelection,
    frame: pd.DataFrame,
    *,
    chart_type: str,
    group_columns: list[str] | None = None,
    plotly_visual_settings: dict[str, Any] | None = None,
) -> dict[str, Any]:
    groups = _plot_groups(frame, group_columns=group_columns)
    image_groups, sampling_note = _sample_plot_groups_for_static_image(
        groups,
        metric.field_name,
        seed_parts=(chart_type, metric.field_name),
    )
    plotly_spec = _build_plotstats_distribution_spec(
        metric,
        image_groups,
        chart_type=chart_type,
        title=f"{metric.display_label} {chart_type}",
        plotly_visual_settings=plotly_visual_settings,
    )
    image = _render_distribution_image(metric, frame, chart_type=chart_type, groups=image_groups)
    if not image and plotly_spec is None:
        return {}
    chart = _static_chart_payload(
        chart_id=f"{chart_type}-{metric.field_name}",
        title=f"{metric.display_label} {chart_type}",
        chart_type=chart_type,
        group_labels=[label for label, _group in groups],
        image=image,
        notes=([sampling_note] if sampling_note else []),
    )
    if plotly_spec is not None:
        chart["plotly_spec"] = plotly_spec
    return chart


def _build_plotstats_histogram_spec(
    metric: ProductionMetricSelection,
    groups: list[tuple[str, pd.DataFrame]],
    *,
    title: str,
    stats_tables: list[dict[str, Any]],
    plotly_visual_settings: dict[str, Any] | None = None,
) -> dict[str, Any] | None:
    payload_groups: list[dict[str, Any]] = []
    all_values: list[float] = []
    for label, group in groups:
        if metric.field_name not in group.columns:
            continue
        values = _finite_numeric_values(group[metric.field_name])
        if not values:
            continue
        payload_groups.append({"group": str(label), "values": values})
        all_values.extend(values)
    if not all_values:
        return None
    bin_count = int(resolve_histogram_bin_count(all_values).get("bin_count") or 0)
    payload: dict[str, Any] = {
        "type": "histogram",
        "title": title,
        "limits": _plotstats_metric_limits(metric),
        "style": {"axis_label_x": metric.display_label, "axis_label_y": "Frequency (%)"},
    }
    if len(payload_groups) == 1:
        payload["values"] = payload_groups[0]["values"]
    else:
        payload["groups"] = payload_groups
    if bin_count > 0:
        payload["bin_count"] = bin_count
    if stats_tables:
        payload["summary_table_rows"] = list(stats_tables[0].get("rows") or [])
    if plotly_visual_settings:
        payload["plotly_visual_settings"] = dict(plotly_visual_settings)
    spec = build_dashboard_plotly_spec(
        payload,
        title=title,
        theme=metroliza_dashboard_plotstats_theme(),
        static=False,
    )
    if spec and plotly_visual_settings:
        apply_dashboard_visual_settings(
            spec,
            payload=payload,
            visual_settings=plotly_visual_settings,
            theme=metroliza_dashboard_plotstats_theme(),
        )
    if spec:
        _apply_histogram_tick_readability(spec)
    return spec


def _build_plotstats_distribution_spec(
    metric: ProductionMetricSelection,
    groups: list[tuple[str, pd.DataFrame]],
    *,
    chart_type: str,
    title: str,
    plotly_visual_settings: dict[str, Any] | None = None,
) -> dict[str, Any] | None:
    labels: list[str] = []
    series: list[list[float]] = []
    for label, group in groups:
        if metric.field_name not in group.columns:
            continue
        values = _finite_numeric_values(group[metric.field_name])
        if not values:
            continue
        labels.append(str(label))
        series.append(values)
    if not series:
        return None

    if chart_type == "violin":
        payload_type = "distribution"
        render_mode = "violin"
    elif chart_type == "box":
        payload_type = "iqr"
        render_mode = "iqr"
    else:
        return None

    payload = {
        "type": payload_type,
        "render_mode": render_mode,
        "title": title,
        "labels": labels,
        "series": series,
        "limits": _plotstats_metric_limits(metric),
        "x_label": "Groups",
        "y_label": metric.display_label,
        "style": {"axis_label_x": "Groups", "axis_label_y": metric.display_label},
    }
    if plotly_visual_settings:
        payload["plotly_visual_settings"] = dict(plotly_visual_settings)
    spec = build_dashboard_plotly_spec(
        payload,
        title=title,
        theme=metroliza_dashboard_plotstats_theme(),
        static=False,
    )
    if spec and plotly_visual_settings:
        apply_dashboard_visual_settings(
            spec,
            payload=payload,
            visual_settings=plotly_visual_settings,
            theme=metroliza_dashboard_plotstats_theme(),
        )
    return spec


def _plotstats_metric_limits(metric: ProductionMetricSelection) -> dict[str, float | None]:
    lsl = _coerce_optional_float(metric.lsl)
    usl = _coerce_optional_float(metric.usl)
    nominal = ((lsl + usl) / 2.0) if lsl is not None and usl is not None and lsl <= usl else None
    return {"lsl": lsl, "nominal": nominal, "usl": usl}


