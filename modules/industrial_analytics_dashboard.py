def _histogram_bins(values: list[float]) -> dict[str, float]:
    if not values:
        return {}
    minimum = min(values)
    maximum = max(values)
    if minimum == maximum:
        padding = max(abs(minimum) * 0.01, 0.5)
        minimum -= padding
        maximum += padding
    binning = resolve_histogram_bin_count(values)
    bin_count = max(1, int(binning.get("bin_count") or 1))
    bin_size = (maximum - minimum) / bin_count
    if bin_size <= 0:
        bin_size = 1.0
    return {"start": minimum, "end": maximum, "size": bin_size}


def _merge_axis_layout(base_layout: dict[str, Any], override: dict[str, Any]) -> None:
    for key, value in override.items():
        if key in {"xaxis", "yaxis"} and isinstance(value, dict):
            axis = base_layout.setdefault(key, {})
            axis.update(value)
            if axis.get("title") is not None and not isinstance(axis.get("title"), dict):
                axis["title"] = {"text": str(axis.get("title"))}
        elif key in {"shapes", "annotations"} and isinstance(value, list):
            base_layout.setdefault(key, [])
            base_layout[key].extend(value)
        else:
            base_layout[key] = value


def _apply_time_series_tick_readability(spec: dict[str, Any], *, chart_type: str) -> None:
    if not chart_type.startswith("time_series"):
        return
    layout = spec.get("layout")
    if not isinstance(layout, dict):
        return
    xaxis = layout.setdefault("xaxis", {})
    if not isinstance(xaxis, dict):
        return
    unique_count = _plotly_trace_unique_x_count(spec.get("data"))
    if unique_count < 16:
        return

    xaxis["automargin"] = True
    xaxis["tickangle"] = -34 if unique_count < 80 else -40
    xaxis["tickfont"] = {"size": 10 if unique_count < 200 else 9}
    xaxis["ticklabeloverflow"] = "hide past div"
    if unique_count >= 36:
        xaxis["ticklabelstep"] = max(2, min(8, int(np.ceil(unique_count / 24))))
        xaxis["nticks"] = max(6, min(12, int(np.ceil(unique_count / max(1, xaxis["ticklabelstep"])))))
    else:
        xaxis["nticks"] = max(8, min(14, int(np.ceil(unique_count / 2))))

    margin = layout.setdefault("margin", {})
    if isinstance(margin, dict):
        margin["b"] = max(int(margin.get("b") or 0), 86)


def _plotly_trace_unique_x_count(traces_payload: Any) -> int:
    if not isinstance(traces_payload, list):
        return 0
    seen: set[str] = set()
    for trace in traces_payload:
        if not isinstance(trace, dict):
            continue
        x_values = trace.get("x")
        if not isinstance(x_values, list):
            continue
        for value in x_values:
            if value is None:
                continue
            seen.add(str(value))
    return len(seen)


