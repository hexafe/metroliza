def _render_summary_cards(summary: dict[str, Any]) -> str:
    markup = []
    for label, value in _summary_card_rows(summary):
        markup.append(
            '<div class="card">'
            f'<div class="card-label">{html.escape(str(label))}</div>'
            f'<div class="card-value">{html.escape(str(value if value not in (None, "") else "n/a"))}</div>'
            '</div>'
        )
    return f'<section class="cards">{"".join(markup)}</section>'


def _summary_int(value: Any) -> int | None:
    try:
        if value in (None, ""):
            return None
        return int(value)
    except (TypeError, ValueError):
        return None


def _friendly_time_bucket(value: Any) -> str:
    bucket = str(value or "").strip()
    if not bucket or bucket.casefold() in {"none", "raw", "raw rows"}:
        return ""
    labels = {
        "minute": "By minute",
        "hour": "Hourly",
        "day": "Daily",
        "week": "Weekly",
        "month": "Monthly",
    }
    return labels.get(bucket.casefold(), bucket.replace("_", " ").title())


def _friendly_aggregation_methods(value: Any) -> str:
    if isinstance(value, str):
        methods = [value]
    elif isinstance(value, (list, tuple, set)):
        methods = [str(item) for item in value]
    else:
        methods = []
    labels = [method.strip().replace("_", " ").title() for method in methods if method.strip()]
    return ", ".join(labels)


def _friendly_group_field_name(value: Any) -> str:
    raw = str(value or "").strip()
    folded = raw.casefold()
    if not raw:
        return ""
    if raw == "GROUP" or folded in _MANUAL_GROUP_FIELD_NAMES:
        return "Manual groups"
    if folded == "reference_cohort":
        return "Pasted reference cohorts"
    return raw.replace("_", " ").title()


def _friendly_group_fields(value: Any) -> str:
    if isinstance(value, str):
        fields = [value]
    elif isinstance(value, (list, tuple, set)):
        fields = list(value)
    else:
        fields = []
    labels: list[str] = []
    seen: set[str] = set()
    for field in fields:
        label = _friendly_group_field_name(field)
        if not label:
            continue
        key = label.casefold()
        if key in seen:
            continue
        seen.add(key)
        labels.append(label)
    return ", ".join(labels)


def _plural_summary_count(count: int, singular: str, plural: str | None = None) -> str:
    return f"{count} {singular if count == 1 else (plural or singular + 's')}"


def _summary_card_rows(summary: dict[str, Any]) -> tuple[tuple[str, Any], ...]:
    rows: list[tuple[str, Any]] = [
        ("Rows", summary.get("source_rows")),
    ]
    aggregate_rows = _summary_int(summary.get("aggregate_rows"))
    if aggregate_rows and aggregate_rows > 0:
        rows.append(("Aggregated output points", aggregate_rows))
    rows.extend(
        [
            ("Metrics", summary.get("metric_count")),
            ("Charts", summary.get("chart_count")),
        ]
    )

    time_bucket = _friendly_time_bucket(summary.get("time_bucket"))
    if time_bucket:
        rows.append(("Time bucket", time_bucket))

    aggregation = _friendly_aggregation_methods(summary.get("aggregation_methods"))
    if aggregation:
        rows.append(("Aggregation", aggregation))

    group_fields = _friendly_group_fields(summary.get("group_fields"))
    if group_fields:
        rows.append(("Groups", group_fields))

    reference_count = _summary_int(summary.get("reference_cohort_count"))
    if reference_count and reference_count > 0:
        rows.append(("Pasted references", reference_count))

    groupstats_metric_count = _summary_int(summary.get("groupstats_metric_count"))
    if groupstats_metric_count and groupstats_metric_count > 0:
        rows.append(
            (
                "Groupstats",
                _plural_summary_count(groupstats_metric_count, "metric"),
            )
        )

    return tuple(rows)


def _render_diagnostics(diagnostics: list[dict[str, Any]]) -> str:
    messages = [
        str(item.get("message") or "").strip()
        for item in diagnostics
        if isinstance(item, dict) and str(item.get("message") or "").strip()
    ]
    if not messages:
        return ""
    rows = "".join(f"<li>{html.escape(message)}</li>" for message in messages)
    label = f"Diagnostics ({len(messages)})"
    return f'<details class="diagnostics"><summary>{html.escape(label)}</summary><ul>{rows}</ul></details>'


def _render_groupstats(groupstats: dict[str, Any]) -> str:
    metrics = groupstats.get("metrics") if isinstance(groupstats.get("metrics"), list) else []
    if not metrics:
        return ""
    cards = []
    for metric in metrics:
        if not isinstance(metric, dict):
            continue
        title = str(metric.get("metric") or metric.get("field_name") or "Metric")
        if metric.get("skipped"):
            reason = str(metric.get("skip_reason") or "skipped").replace("_", " ")
            cards.append(
                '<details class="stats-card">'
                f"<summary>{html.escape(title)}</summary>"
                '<div class="stats-card-body">'
                f"<p>Groupstats skipped: {html.escape(reason)}.</p>"
                "</div>"
                "</details>"
            )
            continue
        descriptive_rows = metric.get("descriptive_stats")
        distribution_rows = metric.get("distribution_rows")
        omnibus_rows = _groupstats_omnibus_rows(metric.get("omnibus"))
        pairwise_rows = metric.get("pairwise_rows")
        posthoc_rows = metric.get("posthoc_rows")
        descriptive = _render_collapsible_table_section(
            "Descriptive stats",
            descriptive_rows,
            columns=("group", "n", "mean", "std", "median", "iqr", "min", "max", "cp", "capability"),
        )
        distribution = _render_collapsible_table_section(
            "Distribution checks",
            distribution_rows,
            columns=(
                "group",
                "n",
                "skewness",
                "excess_kurtosis",
                "normality_test",
                "normality_p_value",
                "normality_status",
            ),
        )
        omnibus = _render_collapsible_table_section(
            "Overall group test",
            omnibus_rows,
            columns=("test_name", "p_value", "effect_size", "effect_type", "significant"),
        )
        pairwise = _render_collapsible_table_section(
            "Pairwise tests",
            pairwise_rows,
            columns=(
                "group_a",
                "group_b",
                "delta_mean",
                "p_value",
                "adjusted_p_value",
                "effect_size",
                "effect_type",
                "significant",
                "test_used",
            ),
        )
        posthoc = _render_collapsible_table_section(
            "Post-hoc tests",
            posthoc_rows,
            columns=(
                "group_a",
                "group_b",
                "method_name",
                "family",
                "adjusted_p_value",
                "effect_size",
                "effect_type",
                "significant",
            ),
        )
        insight = metric.get("primary_insight") if isinstance(metric.get("primary_insight"), dict) else {}
        insight_parts = [
            str(insight.get("headline") or "").strip(),
            str(insight.get("why") or "").strip(),
            str(insight.get("first_action") or "").strip(),
        ]
        insight_text = " ".join(part for part in insight_parts if part).strip()
        insight_markup = (
            f"<p>{html.escape(insight_text)}</p>"
            if insight_text
            else ""
        )
        cards.append(
            '<details class="stats-card">'
            f"<summary>{html.escape(title)}</summary>"
            '<div class="stats-card-body">'
            f"{insight_markup}"
            f"{descriptive}"
            f"{distribution}"
            f"{omnibus}"
            f"{pairwise}"
            f"{posthoc}"
            "</div>"
            "</details>"
        )
    if not cards:
        return ""
    label = _plural_summary_count(len(cards), "metric")
    return (
        '<details class="stats-section">'
        f"<summary>Groupstats ({html.escape(label)})</summary>"
        f'<div class="stats-section-grid">{"".join(cards)}</div>'
        "</details>"
    )


def _groupstats_omnibus_rows(value: Any) -> list[dict[str, Any]]:
    if not isinstance(value, dict) or not value:
        return []
    return [value]


def _render_table(rows: Any, *, columns: tuple[str, ...]) -> str:
    if not isinstance(rows, list) or not rows:
        return "<p>No rows available.</p>"
    header = "".join(f"<th>{html.escape(_table_label(column))}</th>" for column in columns)
    body_rows = []
    for row in rows[:200]:
        if not isinstance(row, dict):
            continue
        cells = "".join(
            f"<td>{html.escape(_format_table_value(row.get(column)))}</td>"
            for column in columns
        )
        body_rows.append(f"<tr>{cells}</tr>")
    if not body_rows:
        return "<p>No rows available.</p>"
    return f"<table><thead><tr>{header}</tr></thead><tbody>{''.join(body_rows)}</tbody></table>"


def _row_count(rows: Any) -> int:
    return len(rows) if isinstance(rows, list) else 0


def _render_collapsible_table_section(
    title: str,
    rows: Any,
    *,
    columns: tuple[str, ...],
) -> str:
    row_count = _row_count(rows)
    label = f"{title} ({_plural_summary_count(row_count, 'row')})"
    return (
        '<details class="stats-subsection">'
        f"<summary>{html.escape(label)}</summary>"
        f"{_render_table(rows, columns=columns)}"
        "</details>"
    )


def _table_label(column: str) -> str:
    return column.replace("_", " ").title()


def _format_table_value(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, float):
        return f"{value:.4g}"
    return str(value)


def _render_chart_shell(chart: dict[str, Any]) -> str:
    chart_id = str(chart.get("id") or "")
    title = str(chart.get("title") or "Chart")
    if not chart_id:
        return ""
    stats_markup = _render_chart_stats_tables(chart.get("stats_tables"))
    notes_markup = _render_chart_notes(chart.get("notes"))
    image = chart.get("image") if isinstance(chart.get("image"), dict) else {}
    has_plotly = isinstance(chart.get("plotly_spec"), dict)
    action_markup = (
        f'<button type="button" class="plotly-expand-trigger" data-chart-id="{html.escape(chart_id)}" '
        f'aria-label="Enlarge chart: {html.escape(title)}">Increase size</button>'
        if has_plotly
        else ""
    )
    snapshot_markup = ""
    if image.get("base64"):
        alt = str(image.get("alt") or title)
        image_markup = (
            f'<img class="chart-image" alt="{html.escape(alt)}" '
            f'src="data:{html.escape(str(image.get("mime_type") or "image/png"))};base64,{image["base64"]}">'
        )
        if has_plotly:
            snapshot_markup = (
                '<details class="chart-snapshot">'
                '<summary>Static snapshot</summary>'
                f"{image_markup}"
                "</details>"
            )
            media_markup = f'<div class="plotly-chart" id="{html.escape(chart_id)}"></div>'
        else:
            media_markup = image_markup
    else:
        media_markup = (
            f'<div class="plotly-chart" id="{html.escape(chart_id)}"></div>'
            if has_plotly
            else ""
        )
    return (
        '<article class="chart-card">'
        '<div class="chart-header">'
        f'<div class="chart-title">{html.escape(title)}</div>'
        f"{action_markup}"
        "</div>"
        f"{media_markup}"
        f"{snapshot_markup}"
        f"{notes_markup}"
        f"{stats_markup}"
        '</article>'
    )


def _render_chart_notes(notes: Any) -> str:
    if not isinstance(notes, list) or not notes:
        return ""
    rows = "".join(
        f"<li>{html.escape(str(note))}</li>"
        for note in notes
        if str(note).strip()
    )
    if not rows:
        return ""
    return f'<ul class="chart-notes">{rows}</ul>'


def _render_chart_stats_tables(stats_tables: Any) -> str:
    if not isinstance(stats_tables, list) or not stats_tables:
        return ""
    table_markup = []
    for table in stats_tables[:6]:
        if not isinstance(table, dict):
            continue
        title = str(table.get("title") or "Stats")
        rows = table.get("rows") if isinstance(table.get("rows"), list) else []
        body = []
        for row in rows[:12]:
            if not isinstance(row, dict):
                continue
            body.append(
                "<tr>"
                f"<td>{html.escape(str(row.get('label') or ''))}</td>"
                f"<td>{html.escape(str(row.get('value') or ''))}</td>"
                "</tr>"
            )
        if not body:
            continue
        table_markup.append(
            '<div class="chart-stats-table">'
            f'<div class="chart-stats-title">{html.escape(title)}</div>'
            "<table><thead><tr><th>Statistic</th><th>Value</th></tr></thead>"
            f"<tbody>{''.join(body)}</tbody></table>"
            "</div>"
        )
    if not table_markup:
        return ""
    label = f"Chart statistics ({_plural_summary_count(len(table_markup), 'table')})"
    return (
        '<details class="chart-stats">'
        f"<summary>{html.escape(label)}</summary>"
        f'<div class="chart-stats-grid">{"".join(table_markup)}</div>'
        "</details>"
    )


