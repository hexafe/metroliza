def _normalize_grouped_histogram_bins(spec: Mapping[str, Any]) -> None:
    for trace in spec.get("data") or []:
        if not isinstance(trace, dict) or str(trace.get("type") or "").casefold() != "bar":
            continue
        x_values = trace.get("x")
        if not isinstance(x_values, list) or not x_values:
            continue
        parsed = [_parse_bin_range_label(value) for value in x_values]
        if not all(item is not None for item in parsed):
            continue
        ranges = [(float(start), float(end), str(label)) for start, end, label in parsed if start is not None and end is not None]
        trace["x"] = [(start + end) / 2.0 for start, end, _label in ranges]
        trace["width"] = [max(end - start, 0.0) for start, end, _label in ranges]
        old_customdata = trace.get("customdata") if isinstance(trace.get("customdata"), list) else []
        customdata = []
        for index, (start, end, label) in enumerate(ranges):
            count = None
            if index < len(old_customdata) and isinstance(old_customdata[index], list) and old_customdata[index]:
                count = old_customdata[index][0]
            customdata.append([start, end, count, label])
        trace["customdata"] = customdata
        trace["hovertemplate"] = (
            "bin=%{customdata[0]:.4g}..%{customdata[1]:.4g}<br>"
            "frequency=%{y:.2%}<br>"
            "count=%{customdata[2]}<extra></extra>"
        )


def _normalize_histogram_bar_trace_y_values(spec: Mapping[str, Any]) -> None:
    for trace in spec.get("data") or []:
        if not isinstance(trace, dict):
            continue
        trace_type = str(trace.get("type") or "").strip().casefold()
        if trace_type == "histogram":
            trace["histnorm"] = "probability"
        if trace_type not in {"bar", "histogram"}:
            continue
        y_values = _finite_trace_values(trace.get("y"))
        if not y_values:
            continue
        total = float(sum(value for value in y_values if value > 0.0))
        max_value = float(max(y_values))
        if total > 1.0 + 1e-9 or max_value > 1.0 + 1e-9:
            denominator = total if total > 0.0 else max_value
            normalized = [float(max(value, 0.0) / denominator) for value in y_values]
        else:
            normalized = [float(max(value, 0.0)) for value in y_values]
        trace["y"] = [float(min(value, 1.0)) for value in normalized]
        trace["hovertemplate"] = str(
            trace.get("hovertemplate")
            or "bin=%{x}<br>frequency=%{y:.2%}<extra></extra>"
        )


_GENERIC_OVERLAY_NAME_PATTERN = re.compile(r"^(?:curve\s+)?overlay\s*\d*$", re.IGNORECASE)


def _normalize_histogram_overlay_traces(spec: Mapping[str, Any]) -> None:
    data = spec.get("data")
    if not isinstance(data, list):
        return
    bin_width = _representative_histogram_bin_width(data)
    overlay_index = 0
    for trace in data:
        if not isinstance(trace, dict) or not _is_histogram_overlay_trace(trace):
            continue
        overlay_index += 1
        trace["name"] = _histogram_overlay_trace_name(trace, overlay_index)
        if bin_width is not None:
            _scale_overlay_trace_to_probability(trace, bin_width)


def _representative_histogram_bin_width(data: list[Any]) -> float | None:
    widths: list[float] = []
    for trace in data:
        if not isinstance(trace, Mapping):
            continue
        trace_type = str(trace.get("type") or "").strip().casefold()
        if trace_type == "bar":
            raw_width = trace.get("width")
            if isinstance(raw_width, list):
                widths.extend(_finite_positive_values(raw_width))
            else:
                width = _optional_float(raw_width)
                if width is not None and width > 0:
                    widths.append(width)
        elif trace_type == "histogram":
            xbins = trace.get("xbins") if isinstance(trace.get("xbins"), Mapping) else {}
            width = _optional_float(xbins.get("size"))
            if width is not None and width > 0:
                widths.append(width)
    if not widths:
        return None
    return float(np.median(np.asarray(widths, dtype=float)))


def _finite_positive_values(values: Any) -> list[float]:
    output: list[float] = []
    if not isinstance(values, list):
        return output
    for value in values:
        numeric = _optional_float(value)
        if numeric is not None and numeric > 0:
            output.append(numeric)
    return output


def _is_histogram_overlay_trace(trace: Mapping[str, Any]) -> bool:
    if str(trace.get("type") or "").strip().casefold() != "scatter":
        return False
    axis, value = _constant_line_axis_and_value(trace)
    if axis and value is not None:
        return False
    name = str(trace.get("name") or "").strip()
    return bool(_GENERIC_OVERLAY_NAME_PATTERN.match(name))


def _histogram_overlay_trace_name(trace: Mapping[str, Any], overlay_index: int) -> str:
    line = trace.get("line") if isinstance(trace.get("line"), Mapping) else {}
    dash = str(line.get("dash") or trace.get("dash") or "").strip().casefold()
    fill = str(trace.get("fill") or "").strip().casefold()
    if fill and fill != "none":
        return "Tail shading"
    if dash and dash not in {"solid", "none"}:
        return "KDE reference"
    return "Selected model curve" if overlay_index == 1 else f"Model curve {overlay_index}"


def _scale_overlay_trace_to_probability(trace: dict[str, Any], bin_width: float) -> None:
    y_values = _finite_trace_values(trace.get("y"))
    if not y_values:
        return
    y_array = np.asarray(y_values, dtype=float)
    if y_array.size == 0:
        return
    scaled = y_array * float(bin_width)
    max_scaled = float(np.nanmax(scaled)) if scaled.size else 0.0
    if max_scaled > 1.0:
        scaled = scaled / max_scaled
    trace["y"] = [float(min(max(value, 0.0), 1.0)) for value in scaled.tolist()]
    trace["hovertemplate"] = str(trace.get("hovertemplate") or "%{x}<br>%{y:.2%}<extra></extra>")


def _format_group_statistics_trace_name(label: str, values: list[float]) -> str:
    if not values:
        return str(label)
    return f"{label} (n={len(values)})"


def _format_plotly_stat_value(value: float | None) -> str:
    if value is None or not math.isfinite(float(value)):
        return ""
    number = float(value)
    magnitude = abs(number)
    if magnitude >= 10_000 or (0.0 < magnitude < 0.001):
        return f"{number:.4g}"
    rounded = Decimal(str(round(number, 12))).quantize(Decimal("0.001"), rounding=ROUND_HALF_UP)
    text = f"{rounded:f}".rstrip("0").rstrip(".")
    return "0" if text in {"", "-0"} else text


def _format_metrology_legend_value(label: str, value: float | None) -> str:
    if value is None or not math.isfinite(float(value)):
        return ""
    precision = 4 if label.strip().casefold() == "mean" else 3
    quantizer = Decimal("1").scaleb(-precision)
    rounded = Decimal(str(round(float(value), 12))).quantize(quantizer, rounding=ROUND_HALF_UP)
    return f"{rounded:.{precision}f}"


def _dedupe_visible_stat_legend_items(spec: Mapping[str, Any]) -> None:
    data = spec.get("data")
    if not isinstance(data, list):
        return
    seen: set[str] = set()
    for trace in data:
        if not isinstance(trace, dict):
            continue
        if trace.get("showlegend", True) is False:
            continue
        name = str(trace.get("name") or "").strip()
        if not _is_canonical_stat_legend_item_name(name):
            continue
        if name in seen:
            trace["showlegend"] = False
            continue
        seen.add(name)


def _is_canonical_stat_legend_item_name(name: str) -> bool:
    left, separator, value = str(name or "").partition("=")
    if not separator or not value.strip():
        return False
    label = left.strip().split(" ")[-1].casefold()
    return label in _REFERENCE_LEGEND_LABELS


def _percentile_sorted(values: list[float], fraction: float) -> float:
    if not values:
        return float("nan")
    if len(values) == 1:
        return float(values[0])
    position = (len(values) - 1) * fraction
    lower = int(math.floor(position))
    upper = int(math.ceil(position))
    if lower == upper:
        return float(values[lower])
    weight = position - lower
    return float(values[lower] * (1.0 - weight) + values[upper] * weight)


def _parse_bin_range_label(value: Any) -> tuple[float, float, str] | None:
    text = str(value or "").strip()
    match = _BIN_RANGE_PATTERN.match(text)
    if match is None:
        return None
    try:
        start = float(match.group(1))
        end = float(match.group(2))
    except ValueError:
        return None
    if not (math.isfinite(start) and math.isfinite(end) and end > start):
        return None
    return start, end, text


def _normalize_reference_trace_names_and_annotations(spec: Mapping[str, Any]) -> None:
    layout = spec.get("layout")
    if not isinstance(layout, dict):
        return
    is_histogram = _is_histogram_plotly_spec(spec)
    existing_annotations = layout.get("annotations")
    annotations_valid = isinstance(existing_annotations, list)
    annotations = existing_annotations if annotations_valid else []
    existing_text = {
        str(annotation.get("text") or "")
        for annotation in annotations
        if isinstance(annotation, Mapping)
    }
    for trace in spec.get("data") or []:
        if not isinstance(trace, dict):
            continue
        label = str(trace.get("name") or "").strip()
        label_key = label.casefold()
        if label_key not in _REFERENCE_LEGEND_LABELS:
            continue
        axis, value = _constant_line_axis_and_value(trace)
        if value is None:
            continue
        display_label = _REFERENCE_LEGEND_DISPLAY_LABELS.get(label_key, label)
        display = f"{display_label}={_format_metrology_legend_value(display_label, value)}"
        trace["name"] = display
        if is_histogram and axis == "x":
            _promote_histogram_reference_trace_to_shape(layout, trace, value)
        if display in existing_text:
            continue
        annotation = _reference_annotation(axis=axis, value=value, text=display, color=_trace_line_color(trace))
        if annotation is not None:
            if not annotations_valid:
                layout["annotations"] = annotations
                annotations_valid = True
            annotations.append(annotation)
            existing_text.add(display)


def _promote_histogram_reference_trace_to_shape(
    layout: dict[str, Any],
    trace: dict[str, Any],
    value: float,
) -> None:
    line = trace.get("line") if isinstance(trace.get("line"), Mapping) else {}
    color = str(line.get("color") or "#111827")
    width = _optional_float(line.get("width")) or 2
    dash = str(line.get("dash") or "dash")
    shapes = layout.setdefault("shapes", [])
    if not isinstance(shapes, list):
        shapes = []
        layout["shapes"] = shapes
    if not _has_histogram_reference_shape(shapes, value):
        shapes.append(
            {
                "type": "line",
                "xref": "x",
                "yref": "paper",
                "x0": value,
                "x1": value,
                "y0": 0,
                "y1": 1,
                "line": {"color": color, "width": width, "dash": dash},
            }
        )
    trace["type"] = "scatter"
    trace["mode"] = "lines"
    trace["x"] = [value, value]
    trace["y"] = [0.0, 0.0]
    trace["visible"] = "legendonly"
    trace["showlegend"] = True
    trace["hoverinfo"] = "skip"


def _has_histogram_reference_shape(shapes: list[Any], value: float) -> bool:
    for shape in shapes:
        if not isinstance(shape, Mapping):
            continue
        if str(shape.get("type") or "").strip().casefold() != "line":
            continue
        if str(shape.get("xref") or "").strip().casefold() != "x":
            continue
        if str(shape.get("yref") or "").strip().casefold() != "paper":
            continue
        x0 = _optional_float(shape.get("x0"))
        x1 = _optional_float(shape.get("x1"))
        if x0 is None or x1 is None:
            continue
        if math.isclose(x0, value, rel_tol=1e-9, abs_tol=1e-12) and math.isclose(
            x1,
            value,
            rel_tol=1e-9,
            abs_tol=1e-12,
        ):
            return True
    return False


def _constant_line_axis_and_value(trace: Mapping[str, Any]) -> tuple[str, float | None]:
    x_values = _finite_trace_values(trace.get("x"))
    y_values = _finite_trace_values(trace.get("y"))
    if len(x_values) >= 2 and all(math.isclose(value, x_values[0]) for value in x_values):
        return "x", x_values[0]
    if len(y_values) >= 2 and all(math.isclose(value, y_values[0]) for value in y_values):
        return "y", y_values[0]
    return "", None


def _finite_trace_values(values: Any) -> list[float]:
    if isinstance(values, np.ndarray):
        iterable = values.tolist()
    elif isinstance(values, (list, tuple)):
        iterable = values
    else:
        return []
    output: list[float] = []
    for value in iterable:
        try:
            number = float(value)
        except (TypeError, ValueError):
            continue
        if math.isfinite(number):
            output.append(number)
    return output


def _reference_annotation(*, axis: str, value: float, text: str, color: str) -> dict[str, Any] | None:
    annotation: dict[str, Any] = {
        "text": text,
        "showarrow": False,
        "font": {"size": 11, "color": color},
        "bgcolor": "#ffffff",
        "bordercolor": "#cbd5e1",
        "borderwidth": 1,
        "borderpad": 3,
        "opacity": 1.0,
    }
    if axis == "x":
        annotation.update({"xref": "x", "yref": "paper", "x": value, "y": 1.04, "yanchor": "bottom"})
        return annotation
    if axis == "y":
        annotation.update(
            {
                "xref": "paper",
                "yref": "y",
                "x": 1.0,
                "y": value,
                "xanchor": "right",
                "yanchor": "top",
                "yshift": -4,
            }
        )
        return annotation
    return None


