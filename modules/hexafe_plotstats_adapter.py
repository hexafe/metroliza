@dataclass(frozen=True)
class HistogramStatsTable:
    """Display-ready histogram statistics rows."""

    title: str
    rows: tuple[tuple[str, str], ...]
    backend: str = "metroliza"

    def as_dict(self) -> dict[str, Any]:
        return {
            "title": self.title,
            "backend": self.backend,
            "rows": [{"label": label, "value": value} for label, value in self.rows],
        }


@dataclass(frozen=True)
class HistogramRenderResult:
    """Rendered histogram image and the stats table embedded in it."""

    png_bytes: bytes
    backend: str
    stats_table: HistogramStatsTable


@dataclass(frozen=True)
class ChartArtifactPngResult:
    """Rendered chart image generated by the plotstats artifact adapter."""

    png_bytes: bytes
    backend: str
    artifact: Mapping[str, Any]


def plotstats_export_charts_enabled() -> bool:
    """Return whether Metroliza should route export chart artifacts through plotstats.

    Plotstats is the default export/dashboard chart path. Operators can set
    ``METROLIZA_PLOTSTATS_EXPORT_CHARTS=0`` or another disabled value to force
    the legacy Metroliza/native renderer path for diagnostics or rollback.
    """

    return env_bool(
        PLOTSTATS_EXPORT_CHARTS_ENV_VAR,
        default=True,
        true_values=_PLOTSTATS_ENABLED_VALUES,
        false_values=FALSE_VALUES | frozenset(_PLOTSTATS_DISABLED_VALUES),
    )


