def build_dashboard_plotly_spec(
    payload: Mapping[str, Any],
    *,
    title: str,
    theme: str | Mapping[str, Any] | None = None,
    static: bool = True,
) -> dict[str, Any] | None:
    """Build a bounded Plotly spec through hexafe-plotstats dashboard adapters.

    The package dependency is optional at import time for development and tests.
    Callers keep their existing static-image fallback when this returns ``None``.
    """

    payload = _payload_with_resolved_histogram_bin_count(payload)

    if plotstats_export_charts_enabled():
        spec = build_plotstats_dashboard_spec(
            payload,
            title=title,
            theme="light" if isinstance(theme, Mapping) else str(theme or "light"),
            static=static,
        )
        if spec:
            return spec

    try:
        from hexafe_plotstats.adapters import plotly_spec_from_metroliza_dashboard_payload
    except Exception:
        return _fallback_dashboard_plotly_spec(payload, title=title, static=static)

    try:
        spec = plotly_spec_from_metroliza_dashboard_payload(
            payload,
            title=title,
            theme=theme or metroliza_dashboard_plotstats_theme(),
            static=static,
        )
    except Exception:
        return _fallback_dashboard_plotly_spec(payload, title=title, static=static)
    if not isinstance(spec, dict):
        return _fallback_dashboard_plotly_spec(payload, title=title, static=static)
    data = spec.get("data")
    if not isinstance(data, list) or not data:
        return _fallback_dashboard_plotly_spec(payload, title=title, static=static)
    layout = spec.get("layout") if isinstance(spec.get("layout"), dict) else {}
    config = spec.get("config") if isinstance(spec.get("config"), dict) else {}
    raw_spec = {
        "data": data,
        "layout": layout,
        "config": config,
        "metadata": spec.get("metadata") if isinstance(spec.get("metadata"), dict) else {},
    }
    _normalize_payload_limit_trace_labels(raw_spec, payload)
    _apply_payload_histogram_bins_to_spec(raw_spec, payload)
    _normalize_payload_group_stat_trace_names(raw_spec, payload)
    _ensure_group_histogram_mean_annotations(raw_spec, payload)
    return _normalize_dashboard_plotly_spec(raw_spec)


def _fallback_dashboard_plotly_spec(
    payload: Mapping[str, Any],
    *,
    title: str,
    static: bool,
) -> dict[str, Any] | None:
    payload_type = str(payload.get("type") or "").strip().casefold()
    if payload_type == "histogram":
        return _fallback_histogram_plotly_spec(payload, title=title, static=static)
    return None


def _fallback_histogram_plotly_spec(
    payload: Mapping[str, Any],
    *,
    title: str,
    static: bool,
) -> dict[str, Any] | None:
    groups = _histogram_payload_groups(payload)
    all_values = np.concatenate([values for _label, values in groups]) if groups else np.asarray([])
    all_values = all_values[np.isfinite(all_values)]
    if not groups or all_values.size == 0:
        return None

    bin_count = _resolved_bin_count(all_values, bin_count=_payload_int(payload.get("bin_count")))
    _counts, bin_edges = np.histogram(all_values, bins=max(1, bin_count))
    centers = ((bin_edges[:-1] + bin_edges[1:]) / 2.0).tolist()
    widths = np.diff(bin_edges).tolist()
    traces: list[dict[str, Any]] = []
    for index, (label, values) in enumerate(groups):
        counts, _edges = np.histogram(values, bins=bin_edges)
        denominator = max(int(values.size), 1)
        y_values = (counts / denominator).astype(float).tolist()
        customdata = [
            [float(start), float(end), int(count), f"{start:.4g}..{end:.4g}"]
            for start, end, count in zip(bin_edges[:-1], bin_edges[1:], counts, strict=False)
        ]
        traces.append(
            {
                "type": "bar",
                "name": str(label),
                "x": centers,
                "y": y_values,
                "width": widths,
                "opacity": 0.72 if len(groups) > 1 else 0.9,
                "marker": {"color": _PLOTLY_GROUP_COLORWAY[index % len(_PLOTLY_GROUP_COLORWAY)]},
                "customdata": customdata,
                "hovertemplate": (
                    "bin=%{customdata[0]:.4g}..%{customdata[1]:.4g}<br>"
                    "frequency=%{y:.2%}<br>"
                    "count=%{customdata[2]}<extra></extra>"
                ),
            }
        )
    traces.extend(_histogram_reference_traces(all_values, limits=payload.get("limits")))

    style = payload.get("style") if isinstance(payload.get("style"), Mapping) else {}
    x_label = str(style.get("axis_label_x") or payload.get("x_label") or "Value")
    spec = {
        "data": traces,
        "layout": {
            "title": {"text": title},
            "barmode": "overlay" if len(groups) > 1 else "relative",
            "xaxis": {"title": {"text": x_label}},
            "yaxis": {"title": {"text": "Frequency (%)"}},
            "legend": {"orientation": "h"},
        },
        "config": {"responsive": True, "displaylogo": False, "staticPlot": bool(static)},
        "metadata": {"kind": "histogram", "histogram_y_mode": "percent"},
    }
    _ensure_group_histogram_mean_annotations(spec, payload)
    return _normalize_dashboard_plotly_spec(spec)


def _histogram_payload_groups(payload: Mapping[str, Any]) -> list[tuple[str, np.ndarray]]:
    raw_groups = payload.get("groups")
    groups: list[tuple[str, np.ndarray]] = []
    if isinstance(raw_groups, list):
        for index, item in enumerate(raw_groups, start=1):
            if not isinstance(item, Mapping):
                continue
            values = _finite_values(item.get("values") or ())
            if values.size:
                groups.append((str(item.get("group") or f"Group {index}"), values))
        return groups
    values = _finite_values(payload.get("values") or ())
    return [("Frequency", values)] if values.size else []


def _histogram_reference_traces(
    values: np.ndarray,
    *,
    limits: Any,
) -> list[dict[str, Any]]:
    traces: list[dict[str, Any]] = []
    limits_mapping = limits if isinstance(limits, Mapping) else {}
    reference_values: list[tuple[str, float | None, str]] = [
        ("Min", float(np.min(values)), "#7c3aed"),
        ("Q1", float(np.quantile(values, 0.25)), "#7c3aed"),
        ("Median", float(np.median(values)), "#0f766e"),
        ("Mean", float(np.mean(values)), "#2563eb"),
        ("Q3", float(np.quantile(values, 0.75)), "#7c3aed"),
        ("Max", float(np.max(values)), "#7c3aed"),
        ("LSL", _optional_float(limits_mapping.get("lsl")), "#b91c1c"),
        ("Nominal", _optional_float(limits_mapping.get("nominal")), "#0f766e"),
        ("USL", _optional_float(limits_mapping.get("usl")), "#b91c1c"),
    ]
    for label, value, color in reference_values:
        if value is None or not math.isfinite(value):
            continue
        formatted = _format_metrology_legend_value(label, value)
        traces.append(
            {
                "type": "scatter",
                "mode": "lines",
                "name": label,
                "x": [value, value],
                "y": [0.0, 1.0],
                "line": {"color": color, "width": 1.5, "dash": "dash"},
                "hovertemplate": f"{label}={formatted}<extra></extra>",
            }
        )
    return traces


def _payload_int(value: Any) -> int | None:
    try:
        parsed = int(value)
    except (TypeError, ValueError):
        return None
    return parsed if parsed > 0 else None


def _optional_float(value: Any) -> float | None:
    try:
        parsed = float(value)
    except (TypeError, ValueError):
        return None
    return parsed if math.isfinite(parsed) else None


def _normalize_payload_limit_trace_labels(spec: Mapping[str, Any], payload: Mapping[str, Any]) -> None:
    limits = payload.get("limits") if isinstance(payload.get("limits"), Mapping) else {}
    if not limits:
        return
    limit_values = {
        "LSL": _optional_float(limits.get("lsl")),
        "USL": _optional_float(limits.get("usl")),
    }
    data = spec.get("data")
    if not isinstance(data, list):
        return
    for trace in data:
        if not isinstance(trace, dict):
            continue
        label = str(trace.get("name") or "").strip()
        label_key = label.casefold().replace("_", " ")
        if not label_key.startswith("limit"):
            continue
        _axis, value = _constant_line_axis_and_value(trace)
        matched_label = _matching_limit_label(value, limit_values)
        if matched_label is None:
            if "1" in label_key and limit_values.get("LSL") is not None:
                matched_label = "LSL"
            elif "2" in label_key and limit_values.get("USL") is not None:
                matched_label = "USL"
        if matched_label is not None:
            trace["name"] = matched_label


def _matching_limit_label(
    value: float | None,
    limit_values: Mapping[str, float | None],
) -> str | None:
    if value is None:
        return None
    for label, limit_value in limit_values.items():
        if limit_value is not None and math.isclose(value, limit_value, rel_tol=1e-9, abs_tol=1e-9):
            return label
    return None


def build_chart_artifact(
    payload: Mapping[str, Any],
    *,
    target: str,
    title: str | None = None,
    theme: str | Mapping[str, Any] | None = None,
    backend: str = "auto",
    include_plotly: bool = True,
    include_png: bool = False,
    static: bool | None = None,
) -> dict[str, Any] | None:
    """Build a plotstats chart artifact when the installed package supports it."""

    try:
        from hexafe_plotstats.adapters import chart_artifact_from_metroliza_payload
    except Exception:
        return None

    payload_mapping = dict(payload)
    if title is not None and not payload_mapping.get("title"):
        payload_mapping["title"] = title
    try:
        artifact = chart_artifact_from_metroliza_payload(
            payload_mapping,
            target=target,
            theme=theme or metroliza_dashboard_plotstats_theme(),
            backend=backend,
            include_plotly=include_plotly,
            include_png=include_png,
            static=static,
        )
    except Exception:
        return None
    return artifact if isinstance(artifact, dict) else None


def build_plotstats_dashboard_spec(
    payload: Mapping[str, Any],
    *,
    title: str,
    theme: str = "light",
    static: bool = True,
) -> dict[str, Any] | None:
    """Build an HTML-dashboard Plotly spec through the new artifact contract."""

    payload = _payload_with_resolved_histogram_bin_count(payload)
    dashboard_theme = metroliza_dashboard_plotstats_theme()
    dashboard_theme["dashboard_theme"] = str(theme or "light")
    artifact = build_chart_artifact(
        payload,
        target="html_dashboard",
        title=title,
        theme=dashboard_theme,
        include_plotly=True,
        include_png=False,
        static=static,
    )
    if not artifact:
        return None
    spec = artifact.get("plotly_spec")
    if not _valid_plotly_spec(spec):
        return None
    _normalize_payload_limit_trace_labels(spec, payload)
    _apply_payload_histogram_bins_to_spec(spec, payload)
    _normalize_payload_group_stat_trace_names(spec, payload)
    _ensure_group_histogram_mean_annotations(spec, payload)
    return _trim_plotly_spec(spec)


def normalize_distribution_stat_legend(
    spec: Mapping[str, Any],
    payload: Mapping[str, Any],
) -> dict[str, Any]:
    """Ensure distribution/IQR Plotly legends expose values for semantic stat items."""

    normalized = dict(spec)
    _normalize_payload_group_stat_trace_names(normalized, payload)
    _dedupe_visible_stat_legend_items(normalized)
    return normalized


def render_chart_artifact_png(
    payload: Mapping[str, Any],
    *,
    target: str = "workbook_image",
    backend: str = "auto",
) -> ChartArtifactPngResult | None:
    """Render a chart PNG through plotstats artifact API when available."""

    artifact = build_chart_artifact(
        payload,
        target=target,
        backend=backend,
        include_plotly=False,
        include_png=True,
        static=True,
    )
    if not artifact:
        return None
    png_bytes = artifact.get("png_bytes")
    if not isinstance(png_bytes, (bytes, bytearray)) or not png_bytes:
        return None
    backend_name = str(artifact.get("backend") or "hexafe-plotstats")
    return ChartArtifactPngResult(
        png_bytes=bytes(png_bytes),
        backend=backend_name,
        artifact=artifact,
    )


def build_histogram_stats_table(
    values: Iterable[Any],
    *,
    title: str = "Parameter",
    backend: str = "metroliza",
    lsl: float | None = None,
    usl: float | None = None,
) -> HistogramStatsTable | None:
    array = _finite_values(values)
    if array.size == 0:
        return None
    package_rows = _histogram_table_rows_from_plotstats(array, lsl=lsl, usl=usl)
    if package_rows:
        rows = _normalize_histogram_capability_rows(package_rows, lsl=lsl, usl=usl)
        resolved_backend = "hexafe-plotstats"
    else:
        table_payload = build_histogram_table_data(_summary_stats(array, lsl=lsl, usl=usl))
        rows = _normalize_histogram_capability_rows(
            tuple((str(label), str(value)) for label, value in table_payload.get("rows", ())),
            lsl=lsl,
            usl=usl,
        )
        resolved_backend = backend
    return HistogramStatsTable(title=str(title or "Parameter"), rows=rows, backend=resolved_backend)


def render_histogram_png(
    values: Iterable[Any],
    *,
    title: str,
    metric_label: str,
    bin_count: int | None = None,
    lsl: float | None = None,
    usl: float | None = None,
) -> HistogramRenderResult | None:
    """Render a histogram PNG through hexafe-plotstats, falling back to local Matplotlib."""

    array = _finite_values(values)
    if array.size == 0:
        return None
    resolved_bin_count = _resolved_bin_count(array, bin_count=bin_count)
    stats_table = build_histogram_stats_table(
        array,
        title="Parameter",
        backend="hexafe-plotstats",
        lsl=lsl,
        usl=usl,
    )
    if stats_table is None:
        return None

    result = _render_with_hexafe_plotstats(
        array,
        title=title,
        metric_label=metric_label,
        bin_count=resolved_bin_count,
        stats_table=stats_table,
        lsl=lsl,
        usl=usl,
    )
    if result is not None:
        return result
    return _render_with_metroliza_fallback(
        array,
        title=title,
        metric_label=metric_label,
        bin_count=resolved_bin_count,
        stats_table=replace(stats_table, backend="metroliza-fallback"),
    )


def _render_with_hexafe_plotstats(
    values: np.ndarray,
    *,
    title: str,
    metric_label: str,
    bin_count: int,
    stats_table: HistogramStatsTable,
    lsl: float | None = None,
    usl: float | None = None,
) -> HistogramRenderResult | None:
    try:
        from hexafe_plotstats import HistogramConfig, build_histogram_payload, render_histogram
        from hexafe_plotstats.models.common import SpecLimits
        from hexafe_plotstats.models.payloads import TableRow
    except Exception:
        return None

    try:
        spec_limits = SpecLimits(lsl=lsl, nominal=_nominal_from_limits(lsl, usl), usl=usl)
        payload = build_histogram_payload(
            values,
            spec_limits=spec_limits,
            config=HistogramConfig(bins=bin_count, density=False, include_fit=True),
            metadata={
                "title": title,
                "axis_labels": {"x": metric_label, "y": "Count"},
            },
        )
        payload = replace(
            payload,
            table_rows=tuple(
                TableRow(label=label, value=value, kind="summary_metric")
                for label, value in stats_table.rows
            ),
        )
        render_result = render_histogram(payload, backend="matplotlib")
        png_bytes = _figure_png_bytes(render_result.fig)
        return HistogramRenderResult(
            png_bytes=png_bytes,
            backend="hexafe-plotstats",
            stats_table=stats_table,
        )
    except Exception:
        return None
    finally:
        _close_plotstats_figure(locals().get("render_result"))


def _render_with_metroliza_fallback(
    values: np.ndarray,
    *,
    title: str,
    metric_label: str,
    bin_count: int,
    stats_table: HistogramStatsTable,
) -> HistogramRenderResult:
    import matplotlib.pyplot as plt

    fig = plt.figure(figsize=(7.4, 3.7))
    try:
        grid = fig.add_gridspec(1, 2, width_ratios=(3.0, 1.35), wspace=0.25)
        ax = fig.add_subplot(grid[0, 0])
        table_ax = fig.add_subplot(grid[0, 1])
        ax.hist(
            values,
            bins=bin_count,
            color=SUMMARY_PLOT_PALETTE["distribution_base"],
            edgecolor=SUMMARY_PLOT_PALETTE["distribution_foreground"],
            alpha=0.82,
        )
        ax.set_title(title, color=SUMMARY_PLOT_PALETTE["annotation_text"])
        ax.set_xlabel(metric_label, color=SUMMARY_PLOT_PALETTE["axis_text"])
        ax.set_ylabel("Count", color=SUMMARY_PLOT_PALETTE["axis_text"])
        ax.grid(
            True,
            axis="y",
            color=SUMMARY_PLOT_PALETTE["grid"],
            linewidth=0.5,
            alpha=0.45,
        )
        for spine in ax.spines.values():
            spine.set_color(SUMMARY_PLOT_PALETTE["axis_spine"])
        ax.tick_params(axis="both", colors=SUMMARY_PLOT_PALETTE["axis_text"])
        _draw_stats_table(table_ax, stats_table)
        fig.subplots_adjust(left=0.08, right=0.98, bottom=0.16, top=0.88, wspace=0.28)
        png_bytes = _figure_png_bytes(fig)
    finally:
        plt.close(fig)
    return HistogramRenderResult(
        png_bytes=png_bytes,
        backend=stats_table.backend,
        stats_table=stats_table,
    )


def _histogram_table_rows_from_plotstats(
    values: np.ndarray,
    *,
    lsl: float | None = None,
    usl: float | None = None,
) -> tuple[tuple[str, str], ...]:
    try:
        from hexafe_plotstats import HistogramConfig, build_histogram_payload
        from hexafe_plotstats.models.common import SpecLimits
    except Exception:
        return ()
    try:
        payload = build_histogram_payload(
            values,
            spec_limits=SpecLimits(lsl=lsl, nominal=_nominal_from_limits(lsl, usl), usl=usl),
            config=HistogramConfig(density=False, include_fit=True),
        )
    except Exception:
        return ()
    rows = []
    for row in getattr(payload, "table_rows", ()) or ():
        label = str(getattr(row, "label", "") or "").strip()
        value = str(getattr(row, "value", "") or "").strip()
        if label:
            rows.append((label, value))
    return tuple(rows)


def _nominal_from_limits(lsl: float | None, usl: float | None) -> float | None:
    if lsl is not None and usl is not None and lsl <= usl:
        return (float(lsl) + float(usl)) / 2.0
    return None


def _normalize_histogram_capability_rows(
    rows: tuple[tuple[str, str], ...],
    *,
    lsl: float | None,
    usl: float | None,
) -> tuple[tuple[str, str], ...]:
    has_lsl = lsl is not None
    has_usl = usl is not None
    has_any_limit = has_lsl or has_usl
    has_two_sided_limits = has_lsl and has_usl
    normalized: list[tuple[str, str]] = []
    seen_labels: set[str] = set()

    for raw_label, raw_value in rows:
        label = str(raw_label or "").strip()
        value = str(raw_value or "").strip()
        label_key = label.casefold().replace(" ", "")
        if label_key == "cp":
            label = "Cp"
            if not has_two_sided_limits:
                value = "N/A"
        elif label_key in {"cpk", "cpu", "cpl"}:
            label = "Cpk"
            if not has_any_limit:
                value = "N/A"
        elif label_key == "nok":
            label = "NOK"
            if not has_any_limit:
                value = "N/A"
        elif label_key in {"nok%", "nokpct"}:
            label = "NOK %"
            if not has_any_limit:
                value = "N/A"
        if label:
            seen_labels.add(label.casefold())
        normalized.append((label, value))

    required_rows: list[tuple[str, str]] = []
    if "cp" not in seen_labels:
        required_rows.append(("Cp", "N/A" if not has_two_sided_limits else ""))
    if "cpk" not in seen_labels:
        required_rows.append(("Cpk", "N/A" if not has_any_limit else ""))
    if not has_any_limit:
        if "nok" not in seen_labels:
            required_rows.append(("NOK", "N/A"))
        if "nok %" not in seen_labels:
            required_rows.append(("NOK %", "N/A"))

    for label, value in required_rows:
        normalized = _insert_histogram_row_before_samples(normalized, (label, value))
    return tuple(normalized)


